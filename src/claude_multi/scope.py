def hook_shim_v3_path(state_root: Path | str) -> Path:
    """The stable protocol-3 hook command path embedded in v2 scopes."""

    return Path(state_root) / HOOK_SHIM_V3_RELATIVE


# A POSIX ``case`` glob for a canonical lowercase UUIDv4 (the managed id and
# the runtime session id); the shim never builds a path from anything else.
_HEX = "[0-9a-f]"
_UUID4_GLOB = "-".join(
    (_HEX * 8, _HEX * 4, "4" + _HEX * 3, "[89ab]" + _HEX * 3, _HEX * 12)
)

# The runtime id is taken only from a payload
# that STARTS with ``{"session_id":"`` (the client's createBaseHookInput
# order). An unanchored ``${payload#*"$key"}`` is quadratic in bash when the
# key follows a large prompt (45 s on 320 KB, measured) — far over the
# compiled 5 s hook timeout; the anchored strip is linear. Every other shape
# (key later, spaced JSON, duplicate key) goes to the launcher.
_HOOK_SHIM_V3_TEMPLATE = """\
#!/bin/sh
# claude-multi hook shim, protocol 3 - stable path embedded in compiled 3.0
# scopes. Regenerated by the launcher; do not edit. The UserPromptSubmit
# event takes a sh fast path that starts no launcher process when this
# runtime session has already seen the scope's lineup generation; it reads
# the runtime id only from a payload that starts with {"session_id":"
# (the client's order), every other payload goes to the launcher. start and
# end pass the launcher's exit status through; every other event exits 0
# (exit 2 on UserPromptSubmit blocks the user's prompt). Launcher stdout is
# forwarded only when the launcher exits 0. premodel fails closed: a missing
# launcher or a non-zero exit prints a fixed PreModelSwitch deny.
state=@Q_STATE@
launcher=@Q_CMD@
if [ ! -x "$launcher" ]; then
    launcher=$(command -v claude-multi 2>/dev/null) || launcher=
fi
deny=
case "${2-}" in
    start|end) keep_status=1 ;;
    premodel) keep_status=0; deny=@Q_PREMODEL_DENY@ ;;
    *) keep_status=0 ;;
esac
if [ "$#" -eq 8 ] && [ "$1" = session-event ] && [ "$2" = prompt ] \\
    && [ "$3" = --managed-id ] && [ "$5" = --launch-epoch ] \\
    && [ "$7" = --hook-protocol ] && [ "$8" = 3 ]; then
    payload=$(cat)
    key='"session_id":"'
    q='"'
    rid=
    case $payload in
        *"$key"*"$key"*) ;;
        '{'"$key"*)
            rid=${payload#'{'"$key"}
            rid=${rid%%"$q"*}
            ;;
    esac
    case $rid in
        @UUID@) ;;
        *) rid= ;;
    esac
    mid=
    case $4 in
        @UUID@) mid=$4 ;;
    esac
    if [ -n "$mid" ] && [ -n "$rid" ]; then
        gen=
        seen=
        if [ -f "$state/scopes/$mid/lineup.gen" ]; then
            IFS= read -r gen < "$state/scopes/$mid/lineup.gen" || :
        fi
        if [ -f "$state/notice/$rid.seen" ]; then
            IFS= read -r seen < "$state/notice/$rid.seen" || :
        fi
        if [ -n "$gen" ] && [ "$gen" = "$seen" ]; then
            exit 0
        fi
    fi
    if [ -z "$launcher" ]; then
        echo 'claude-multi hook shim: no claude-multi launcher found' >&2
        exit 0
    fi
    out=$(printf '%s\\n' "$payload" | "$launcher" "$@")
    status=$?
else
    if [ -z "$launcher" ]; then
        echo 'claude-multi hook shim: no claude-multi launcher found' >&2
        if [ -n "$deny" ]; then
            printf '%s\\n' "$deny"
        fi
        exit 0
    fi
    out=$("$launcher" "$@")
    status=$?
fi
if [ "$status" -eq 0 ]; then
    if [ -n "$out" ]; then
        printf '%s\\n' "$out"
    fi
    exit 0
fi
echo "claude-multi hook shim: launcher exited with status $status (event ${2-unknown}); output dropped" >&2
if [ "$keep_status" -eq 1 ]; then
    exit "$status"
fi
if [ -n "$deny" ]; then
    printf '%s\\n' "$deny"
fi
exit 0
"""


# The shim's fixed premodel deny (one line, no single quote, so the
# ``shlex.quote`` above is a plain single-quoted word).
_SHIM_PREMODEL_DENY = hooks.premodel_fail_closed_response(
    "claude-multi premodel failed: launcher unavailable — run claude-multi doctor"
).rstrip("\n")


def hook_shim_v3_text(state_root: Path | str, resolved_command: str) -> bytes:
    """The protocol-3 hook shim bytes for ``state_root`` (pure; spec §3.7).

    The state root is embedded (shell-quoted) so the ``UserPromptSubmit``
    fast path can compare ``scopes/<mid>/lineup.gen`` with
    ``notice/<rid>.seen`` without starting a process other than ``cat``.
    The shim never ``exec``s: it forwards launcher stdout only on exit 0,
    passes the status through for ``start``/``end`` only, and exits 0 for
    every other event (including unknown ones and an older launcher that
    rejects the protocol-3 argv). ``premodel`` fails closed: a missing
    launcher or a non-zero exit prints the fixed
    :func:`hooks.premodel_fail_closed_response` deny instead of nothing.
    """

    if not resolved_command:
        raise ScopeError("cannot write the hook shim without a resolved command")
    values = {
        "Q_STATE": shlex.quote(str(Path(state_root))),
        "Q_CMD": shlex.quote(resolved_command),
        "UUID": _UUID4_GLOB,
        "Q_PREMODEL_DENY": shlex.quote(_SHIM_PREMODEL_DENY),
    }
    # One pass, so a placeholder-shaped substring inside a substituted path
    # is never substituted again.
    return re.sub(
        r"@(Q_STATE|Q_CMD|UUID|Q_PREMODEL_DENY)@", lambda match: values[match.group(1)], _HOOK_SHIM_V3_TEMPLATE
    ).encode("utf-8")


def ensure_hook_shim_v3(state_root: Path | str, resolved_command: str) -> Path:
    """Write/refresh ``<state>/bin/claude-multi-hook-3``; return its path.

    Same discipline as :func:`ensure_hook_shim` (refuse an empty command,
    private ``bin/``, atomic write only on change, 0700 repaired
    unconditionally). The two shims are independent files: neither ensure
    touches the other's path.
    """

    return _ensure_executable_shim(
        hook_shim_v3_path(state_root), hook_shim_v3_text(state_root, resolved_command)
    )


@dataclass(frozen=True)
class OfferedLine:
    """One offered line of the merged (catalog ∪ custom) view."""

    key: str
    entry: Mapping[str, Any]
    provider_id: str
    provider: Mapping[str, Any]
    family: str
    source: str  # "catalog" | "custom" (a custom synthetic entry carries ``family``)
    origin: str = "catalog"  # catalog | legacy-custom | operator | operator-migrated

    @property
    def t2(self) -> bool:
        return self.origin in profile.OPERATOR_ORIGINS


@dataclass(frozen=True)
class LineView:
    """The single merged-view seam.

    Built by :func:`line_view` from one ``LineupCatalog`` — for launch
    callers the ``custom.merge_docs`` result (``Runtime.ordinary_docs``), so custom
    lines and providers are included. The lead set, the agent set, the
    fence, the family defaults and the process ``env_unset`` provider
    secret names all come from here; nothing in the v2 path reads the
    catalog lines or calls ``settings.line_offered`` elsewhere.
    """

    lines: tuple[OfferedLine, ...]  # offered lines only, models-v2 order
    secret_env_names: tuple[str, ...]  # sorted ``env:`` secret_ref names, every provider


def _secret_env_name(provider: Mapping[str, Any]) -> str | None:
    transport = provider.get("transport")
    auth = transport.get("auth") if isinstance(transport, Mapping) else None
    ref = auth.get("secret_ref") if isinstance(auth, Mapping) else None
    if isinstance(ref, str) and ref.startswith("env:") and len(ref) > 4:
        return ref[4:]
    return None


def line_view(cat: profile.LineupCatalog, eff: settings_mod.Effective) -> LineView:
    """Every usable line (enabled provider and usable route), in line order."""

    lines: list[OfferedLine] = []
    for key, entry in cat.lines.items():
        if not settings_mod.line_offered(key, entry, eff):
            continue
        provider_id = entry["provider"]
        provider = cat.providers.get(provider_id)
        if provider is None:
            raise ScopeError(f"line {key!r} names unknown provider {provider_id!r}")
        lines.append(
            OfferedLine(
                key=key,
                entry=entry,
                provider_id=provider_id,
                provider=provider,
                family=cat.line_family(key, entry),
                # Origin mapping: "custom" (the persisted lead-set value)
                # is legacy-custom only; operator origins rank as catalog.
                source="custom" if cat.origin(key) == "legacy-custom" else "catalog",
                origin=cat.origin(key),
            )
        )
    names = {
        name
        for provider in cat.providers.values()
        if (name := _secret_env_name(provider)) is not None
    }
    # Every declared T2 secret name, rendered or not (invalid and
    # unapproved declarations included), is scrubbed from managed launches.
    names |= set(getattr(cat, "extra_secret_names", frozenset()))
    return LineView(lines=tuple(lines), secret_env_names=tuple(sorted(names)))


def _line_selectors_v2(line: OfferedLine) -> list[tuple[str | None, str]]:
    """``(effort | None, selector)`` per selector of an offered line.

    The row shape follows the line's own ``efforts`` shape, as
    ``catalog.line_selectors`` does: list-shaped
    (client-effort, custom synthetic lines included whatever their
    provider's adapter) is one row with no effort; map-shaped is one row per
    declared effort in ``profile.EFFORT_ORDER``, each through
    ``profile.binding_selector`` (the single selector rule). These are the
    line selectors; an agent's class is decided by ``profile.role_window``.
    """

    entry = line.entry
    if isinstance(entry["efforts"], (list, tuple)):
        return [(None, entry["selector"])]
    return [
        (effort, profile.binding_selector(entry, line.provider, effort, lead=False)[0])
        for effort in profile.declared_efforts(entry)
    ]


def _agent_forms(line: OfferedLine, policy: profile.WindowPolicy) -> list[str]:
    """Every line selector of an agents-capable line plus the selector an
    agent of it runs on under ``policy`` (the same alias without ``[1m]``
    when its provider bound is below the session window)."""

    context = line.entry["context"]
    forms: list[str] = []
    for _effort, selector in _line_selectors_v2(line):
        decided = profile.role_window(
            selector, client_tokens=context["client_tokens"], provider_tokens=context["provider_tokens"],
            policy=policy, decide=True,
        ).selector
        forms += [selector, decided]
    return forms


@dataclass(frozen=True)
class LeadSetRow:
    """One ``/model`` row of the lead set (§3.3)."""

    key: str
    provider: str
    family: str
    display: str
    selector: str
    effort: str | None  # gateway-effort rows only
    label: str
    client_tokens: int
    provider_tokens: int
    scalar_tokens: int | None
    validated_tokens: int
    source: str  # "catalog" | "custom"
    origin: str = "catalog"  # compile-only: free-form family labels confer no adapter defaults


@dataclass(frozen=True)
class Fence:
    """The split fence: lead set, agent set, fallback-only."""

    lead_class: str
    lead_set: tuple[LeadSetRow, ...]
    agent_set: tuple[str, ...]  # sorted, unique
    fallback_only: tuple[str, ...]  # sorted
    available_models: tuple[str, ...]  # sorted union

    @property
    def lead_selectors(self) -> frozenset[str]:
        return frozenset(row.selector for row in self.lead_set)


def catalog_meta_v2(docs: Mapping[str, Any]) -> CatalogMeta:
    """:class:`CatalogMeta` from v2 data only (no ``docs["models"]`` view read)."""

    lines = (docs["models-v2"] if "models-v2" in docs else docs["models"])["models"]
    selectors = {
        selector
        for entry in lines.values()
        for _effort, selector, _contract in catalog_mod.line_selectors(entry)
    }
    return CatalogMeta(
        base_settings=dict(docs["settings"]),
        client_selectors=tuple(sorted(selectors)),
        generic_agent_aliases=tuple(
            docs["native-contract"]["generic_agent_aliases"]["values"]
        ),
        gateway_base_url=endpoint.gateway_endpoint(docs["gateway"]).base_url,
    )


def _lead_rows(
    view: LineView, lead_class: str | None, lead_providers: Iterable[str] | None
) -> tuple[LeadSetRow, ...]:
    rows: list[LeadSetRow] = []
    for line in view.lines:
        entry = line.entry
        if not profile.lead_set_member(entry, line.provider_id, lead_class, lead_providers):
            continue
        context = entry["context"]
        for effort, selector in _line_selectors_v2(line):
            label = " · ".join(
                [
                    entry["display"],
                    *([effort] if effort else []),
                    line.family,
                    profile.format_tokens(context["client_tokens"]),
                ]
            )
            rows.append(
                LeadSetRow(
                    key=line.key,
                    provider=line.provider_id,
                    family=line.family,
                    display=entry["display"],
                    selector=selector,
                    effort=effort,
                    label=label,
                    client_tokens=context["client_tokens"],
                    provider_tokens=context["provider_tokens"],
                    scalar_tokens=context.get("scalar_tokens"),
                    validated_tokens=context.get("validated_tokens", 0),
                    source=line.source,
                    origin=line.origin,
                )
            )
    counts: dict[str, int] = {}
    for row in rows:
        counts[row.label] = counts.get(row.label, 0) + 1
    return tuple(
        LeadSetRow(**{**row.__dict__, "label": f"{row.label} · {row.key}"})
        if counts[row.label] > 1
        else row
        for row in rows
    )


def lead_set_rows(
    lineup: profile.ResolvedLineup,
    cat: profile.LineupCatalog,
    eff: settings_mod.Effective,
) -> tuple[LeadSetRow, ...]:
    """Lead-capable offered lines of the lead's class, narrowed by ``lead_providers``.

    Rows follow ``models-v2`` line order, then ``profile.EFFORT_ORDER``.
    """

    return _lead_rows(line_view(cat, eff), lineup.lead_class, lineup.lead_providers)


def _agent_set(view: LineView, policy: profile.WindowPolicy, lineup: profile.ResolvedLineup | None = None,
               extra: Iterable[str] = ()) -> tuple[str, ...]:
    """The agent set: T1 keeps every selector of every
    offered agents-capable line, plus the selector an agent of it runs on
    under ``policy`` (the 200K-class alias of a line whose provider bound is
    below the session window); a T2 (operator) line contributes only the
    selectors of agents actually bound in ``lineup`` (already through the
    gate) and ``extra`` (an eligible explicitly configured workflow
    default). An unrelated qualification never widens a fence. The selector
    of every agent bound on an offered line is in the set, so a
    record-authority compile of a session whose unchanged agent keeps its
    recorded class still passes the fence assertion; a line that is not
    offered contributes nothing."""

    offered = {line.key for line in view.lines}
    bound = set()
    if lineup is not None:
        bound = {agent.binding.selector for agent in lineup.agents.values() if agent.binding.key in offered}
    return tuple(
        sorted(
            {
                selector
                for line in view.lines
                if not line.t2 and "agents" in line.entry["capabilities"]
                for selector in _agent_forms(line, policy)
            }
            | bound
            | set(extra)
        )
    )


def agent_set(cat: profile.LineupCatalog, eff: settings_mod.Effective,
              policy: profile.WindowPolicy | None = None) -> tuple[str, ...]:
    """Every selector of every offered agents-capable T1 line and the
    selector its agents run on under ``policy`` (the window ceiling without
    one); T2 selectors enter a fence only as bound eligible agents."""

    return _agent_set(line_view(cat, eff), policy or profile.default_policy(eff))


def fallback_only(rows: Iterable[LeadSetRow]) -> tuple[str, ...]:
    """The refusal-fallback targets for an Anthropic-family lead set.

    ``{w + "[1m]" for w in catalog.REFUSAL_FALLBACK_WIRES}`` minus the lead
    set, emitted iff some lead-set row is of family ``anthropic`` ("the lead
    set contains opus or fable", stated on families).
    """

    rows = tuple(rows)
    if not any(row.provider == "anthropic" or (row.origin == "catalog" and row.family == _FAMILY_ANTHROPIC)
               for row in rows):
        return ()
    lead = {row.selector for row in rows}
    return tuple(
        sorted({wire + "[1m]" for wire in catalog_mod.REFUSAL_FALLBACK_WIRES} - lead)
    )


def fence_gaps(available_models: Iterable[str], selectors: Iterable[str]) -> tuple[str, ...]:
    """Sorted selectors not in ``available_models`` (exact membership, never a prefix).

    Shared by the compile assertion, the per-seed probe and doctor's
    "fence does not cover the bindings" BLOCK.
    """

    available = frozenset(available_models)
    return tuple(sorted({selector for selector in selectors if selector not in available}))


def _fence_policy(rows: Iterable[LeadSetRow], eff: settings_mod.Effective, percent: int) -> profile.WindowPolicy:
    """The session policy over a fence's lead-set rows (``profile.window_policy``
    with the effective window ceiling): the one window the compiled env, the
    agent set and the workflow default share."""

    return profile.window_policy(
        ((row.provider_tokens, row.client_tokens, row.scalar_tokens) for row in rows),
        percent, ceiling=profile.window_ceiling(eff),
    )


def _compile_fence(
    lineup: profile.ResolvedLineup, cat: profile.LineupCatalog, view: LineView, eff: settings_mod.Effective
) -> Fence:
    rows = _lead_rows(view, lineup.lead_class, lineup.lead_providers)
    if not rows:
        raise ScopeError(
            f"lead set for class {lineup.lead_class!r} is empty "
            "(providers disabled or narrowed away)"
        )
    lead_selector = lineup.lead.binding.selector
    if lead_selector not in {row.selector for row in rows}:
        raise ScopeError(
            f"lead selector {lead_selector!r} is not in the lead set of class "
            f"{lineup.lead_class!r} (line not offered, provider disabled or narrowed away)"
        )
    policy = _fence_policy(rows, eff, lineup.policy.percent if lineup.policy is not None else eff.compaction_percent)
    workflow_default = _configured_workflow_default(cat, view, eff, policy)
    agents = _agent_set(view, policy, lineup, () if workflow_default is None else (workflow_default,))
    fallback = fallback_only(rows)
    if set(fallback) & {row.selector for row in rows}:
        raise ScopeError("fallback-only selectors overlap the lead set")
    available = tuple(sorted({row.selector for row in rows} | set(agents) | set(fallback)))
    return Fence(
        lead_class=lineup.lead_class,
        lead_set=rows,
        agent_set=agents,
        fallback_only=fallback,
        available_models=available,
    )


def compile_fence(
    lineup: profile.ResolvedLineup,
    cat: profile.LineupCatalog,
    eff: settings_mod.Effective,
) -> Fence:
    """The split fence plus the lead and fallback assertions (ScopeError)."""

    return _compile_fence(lineup, cat, line_view(cat, eff), eff)


def _configured_workflow_default(cat: profile.LineupCatalog, view: LineView, eff: settings_mod.Effective,
                                policy: profile.WindowPolicy) -> str | None:
    """The explicitly configured workflow selector, regardless of its origin
    or capability recommendations. It is the only unbound operator selector
    a fence gains. A problem is reported by :func:`compile_lineup_scope`."""

    if eff.workflow_default_binding is None:
        return None
    try:
        return _workflow_default(cat, view, eff, policy)
    except ScopeError:
        return None


def _workflow_default(
    cat: profile.LineupCatalog, view: LineView, eff: settings_mod.Effective, policy: profile.WindowPolicy,
) -> str | None:
    role = _workflow_default_window(cat, view, eff, policy)
    return None if role is None else role.selector


def _workflow_default_window(
    cat: profile.LineupCatalog, view: LineView, eff: settings_mod.Effective, policy: profile.WindowPolicy,
) -> profile.RoleWindow | None:
    binding = eff.workflow_default_binding
    if binding is None:
        return None
    model, effort = binding["model"], binding["effort"]
    try:
        resolution = cat.resolve_key(model)
    except catalog_mod.CatalogError as exc:
        raise ScopeError(f"{_WORKFLOW_FIELD}.model: {exc}") from exc
    if resolution.key is None:
        raise ScopeError(f"{_WORKFLOW_FIELD}.model: {resolution.notice}")
    key = resolution.key
    line = next((item for item in view.lines if item.key == key), None)
    entry = cat.lines.get(key)
    if entry is None:
        raise ScopeError(f"{_WORKFLOW_FIELD}.model: line {key!r} is not in the catalog")
    if line is None:
        raise ScopeError(
            f"{_WORKFLOW_FIELD}.model: line {key!r} is not offered "
            f"({eff.unavailable_lines.get(key, 'its provider is disabled in Settings')})"
        )
    if effort == profile.ULTRACODE:
        raise ScopeError(f"{_WORKFLOW_FIELD}.effort: 'ultracode' is lead-only")
    available = profile.available_efforts(entry, cat.agent_efforts)
    if effort not in available:
        raise ScopeError(
            f"{_WORKFLOW_FIELD}.effort: {effort!r} is not supported by line {key!r} "
            f"and the native client (available {list(available)})"
        )
    if isinstance(entry["efforts"], (list, tuple)) and effort != entry["default_effort"]:
        # One selector cannot encode a separately selected workflow effort.
        raise ScopeError(
            f"{_WORKFLOW_FIELD}.effort: line {key!r} is client-effort (one selector); "
            f"a workflow default runs at its default effort {entry['default_effort']!r}, "
            f"never {effort!r}"
        )
    if cat.origin(key) in profile.OPERATOR_ORIGINS:
        # Only actual routing and representability problems refuse. Tool
        # and qualification evidence belongs to optional diagnostics.
        gate = cat.agent_gate
        recorded = bool(gate is not None and gate.mode == profile.AGENT_MODE_RECORD
                        and gate.workflow_default == (model, effort))
        verdict = profile.agent_eligibility(
            entry, key=key, slot=None, effort=effort,
            facts=gate.facts.get(key) if gate is not None else None,
            agent_efforts=cat.agent_efforts,
            mode=gate.mode if gate is not None else profile.AGENT_MODE_CURRENT,
            recorded=recorded, use=profile.WORKFLOW_USE, policy=policy,
            family=cat.line_family(key, entry), known_families=cat.known_families,
        )
        if not verdict.eligible:
            raise ScopeError(
                f"{_WORKFLOW_FIELD}.model: {key} is not agent-eligible ({verdict.reasons[0]}) — {verdict.remedy}"
            )
    # A workflow agent is an agent: its class follows the session window
    # like a bound cm-* agent's.
    context = entry["context"]
    return profile.role_window(
        profile.binding_selector(entry, line.provider, effort, lead=False)[0],
        client_tokens=context["client_tokens"], provider_tokens=context["provider_tokens"],
        policy=policy, decide=True,
    )


def workflow_default_selector(
    cat: profile.LineupCatalog, eff: settings_mod.Effective, *, policy: profile.WindowPolicy | None = None,
) -> str | None:
    """The selector of Settings ``workflow_default_binding`` (None = off).

    The key resolves through ``resolve_key`` (retired → successor); the line
    must have a usable route and supported effort (never ``ultracode``),
    and a client-effort line only at its default effort. Capability and
    evidence recommendations are optional diagnostics.
    Its class follows the session window like an agent's
    (``policy``; the window ceiling without one). Fence membership is
    asserted by the compile. Every failure is a :class:`ScopeError` naming
    ``Settings workflow_default_binding.model`` or ``.effort``.
    """

    return _workflow_default(cat, line_view(cat, eff), eff, policy or profile.default_policy(eff))


def workflow_default_window(
    cat: profile.LineupCatalog, eff: settings_mod.Effective, *, policy: profile.WindowPolicy,
) -> profile.RoleWindow | None:
    """The workflow default's selector, class and effective window under the
    session ``policy`` (None = off); refuses like :func:`workflow_default_selector`."""

    return _workflow_default_window(cat, line_view(cat, eff), eff, policy)


def workflow_default_warnings(
    cat: profile.LineupCatalog, eff: settings_mod.Effective, *, policy: profile.WindowPolicy,
) -> tuple[profile.Finding, ...]:
    """Diagnostics for the explicitly selected workflow default.

    Technical representability and route problems still raise ScopeError.
    Mutable attestations are returned for presentation only, never written
    into agent files, the fence or hashed lineup text.
    """

    role = workflow_default_window(cat, eff, policy=policy)
    binding = eff.workflow_default_binding
    if role is None or binding is None:
        return ()
    key = cat.resolve_key(binding["model"]).key
    entry = cat.lines[key]
    effort = binding["effort"]
    if cat.origin(key) in profile.OPERATOR_ORIGINS:
        gate = cat.agent_gate
        verdict = profile.agent_eligibility(
            entry, key=key, slot=None, effort=effort,
            facts=gate.facts.get(key) if gate is not None else None,
            agent_efforts=cat.agent_efforts,
            mode=gate.mode if gate is not None else profile.AGENT_MODE_CURRENT,
            recorded=bool(gate is not None and gate.mode == profile.AGENT_MODE_RECORD
                          and gate.workflow_default == (binding["model"], effort)),
            use=profile.WORKFLOW_USE, policy=policy,
            family=cat.line_family(key, entry), known_families=cat.known_families,
        )
        warnings = list(verdict.warnings)
    else:
        warnings = list(profile.binding_warnings(
            entry, key=key, slot=None, effort=effort, family=cat.line_family(key, entry),
            known_families=cat.known_families,
            admitted=entry.get("status", "active") != "new" or key in eff.admitted_lines))
        problem = profile.agent_window_problem(
            profile.binding_agent_selector(entry, effort), entry["context"]["provider_tokens"],
            policy=policy, client_tokens=entry["context"]["client_tokens"])
        if problem:
            warnings.append(profile.Finding("context-risk", None, f"{key}: {problem}", "workflow context overflow risk"))
    return tuple(profile.Finding(finding.code, finding.slot, f"workflow default: {finding.message}",
                                 f"workflow default: {finding.compact}") for finding in warnings)


def _check_generation(generation: int) -> int:
    if (
        not isinstance(generation, int)
        or isinstance(generation, bool)
        or not 1 <= generation <= lineup_files.GENERATION_MAX
    ):
        raise ScopeError(
            f"lineup_generation must be an integer in 1-{lineup_files.GENERATION_MAX}, "
            f"not {generation!r}"
        )
    return generation


def _route_cell(cell: profile.RouteCell) -> str:
    text = cell.reviewer or "—"
    if cell.reason:
        text += f" ({cell.reason})"
    if cell.same_family:
        text += " (same-family)"
    elif cell.independence_unknown:
        text += " (independence unknown)"
    if cell.only_other_family:
        text += " (only other-family)"
    return text


def routing_table_lines(lineup: profile.ResolvedLineup) -> list[str]:
    """The ``## Review routing`` table of ``lineup.md`` (header and one row per author).

    ``/cm review`` prints these exact rows,
    so the in-session review follows the table the lead already reads.
    """

    lines = ["| Author | Normal change | High-stakes change |", "|---|---|---|"]
    for row in lineup.routing.rows:
        author = profile.label(row.author) if row.author == profile.LEAD_ROLE else row.author
        lines.append(
            f"| {author} ({row.family}) | {_route_cell(row.normal)} | {_route_cell(row.high)} |"
        )
    return lines


def _exhaustion_lines(lineup: profile.ResolvedLineup) -> list[str]:
    """Cross-provider fallback per function."""

    by_function: dict[str, list[profile.ResolvedAgent]] = {}
    for agent in lineup.agents.values():
        by_function.setdefault(agent.role.function, []).append(agent)
    lines: list[str] = []
    for function, agents in by_function.items():
        providers: dict[str, list[str]] = {}
        for agent in agents:
            providers.setdefault(agent.binding.provider, []).append(f"`{agent.role.id}`")
        listed = "; ".join(f"{provider}: {', '.join(ids)}" for provider, ids in providers.items())
        if len(providers) > 1:
            lines.append(f"- {function}: {listed} — reroute to the grade on another provider.")
        else:
            lines.append(
                f"- {function}: {listed} — no other-provider grade; ask the operator for "
                "`/cm profile claude` (or another profile that avoids that provider) or "
                "`/cm set <agent>=<model>:<effort>`, then `/reload-plugins`."
            )
    return lines


def lineup_md_bytes(
    lineup: profile.ResolvedLineup,
    fence: Fence,
    eff: settings_mod.Effective,
    *,
    generation: int,
    no_subagents: bool,
    default_row_model: str | None = None,
    workflow_default: str | None = None,
    worktree_available: bool = True,
) -> bytes:
    """``<scope>/lineup.md``.

    ``default_row_model`` is the compiled ``ANTHROPIC_DEFAULT_OPUS_MODEL``
    (the picker's built-in Default row); ``workflow_default``
    the compiled ``CLAUDE_CODE_SUBAGENT_MODEL``; ``worktree_available`` False
    marks the writer grades unavailable (a session cwd outside a git work
    tree). Over :data:`LINEUP_MD_MAX_BYTES` → :class:`ScopeError`.
    """

    _check_generation(generation)
    lead = lineup.lead.binding
    name = lineup.name if lineup.name is not None else "ad-hoc direct"
    lines = [
        f"# claude-multi lineup (lineup_generation {generation})",
        "",
        f"Profile: {name} · lead class {lineup.lead_class} "
        f"({profile.format_tokens(lead.client_context_tokens)}) · providers: "
        f"{lineup.spread_text()}",
        "",
        "## Lead",
        f"- lead: {lead.display} · {lead.effort} · {lead.family} · `{lead.selector}`",
        f"- /model offers only the lead set ({len(fence.lead_set)} entries); any other "
        "model needs a relaunch with another profile.",
    ]
    if default_row_model is not None and default_row_model not in fence.lead_selectors:
        lines.append(
            f"- /model's built-in Default row is `{default_row_model}`, outside this "
            "lead set; it is refused."
        )
    lines += ["", "## Agents"]
    if lineup.is_direct:
        lines.append(
            "- none: this session has no cm-* agents; do the work yourself or change "
            "the lineup with /cm."
        )
    else:
        for rid, agent in lineup.agents.items():
            binding = agent.binding
            suffix = "" if agent.lead_step else " · not a step up from the lead"
            if not worktree_available and agent.role.isolation == "worktree":
                suffix += f" · {WRITER_UNAVAILABLE_NOTE}"
            lines.append(
                f"- `{rid}`: {binding.display} · {binding.effort} · {binding.family} · "
                f"`{binding.selector}`{suffix}"
            )
        if lineup.unbound:
            lines.append("- not bound: " + ", ".join(f"`{rid}`" for rid in lineup.unbound))
    if workflow_default is not None:
        # Pinned by the SettingsEnvPlacementProbe case (iii); the same line
        # as the lead appendix.
        lines.append(compiler.workflow_default_line(workflow_default, lineup.native_agents))
    if no_subagents:
        lines.append(
            "- delegation is disabled for this session (--no-subagents): the Agent tool "
            "is denied and workflows are off."
        )
    if lineup.agents:
        lines += ["", "## Provider exhaustion"]
        lines += _exhaustion_lines(lineup)
    lines += ["", "## Review routing", *routing_table_lines(lineup)]
    lines += [
        "",
        f"Review rounds: at most {eff.review_round_cap} per change set; then decide "
        "yourself and report open disagreement to the operator.",
        "",
        "## Rules",
        f"- Trust the lineup with the highest lineup_generation; this one is generation "
        f"{generation}.",
        "- After a lineup change, run `/reload-plugins` before spawning: until then new "
        "spawns keep the previous bindings. Running agents keep their model.",
        "- Never SendMessage-continue an agent spawned under an earlier lineup_generation: "
        "spawn it fresh with a self-contained brief. A round-2 review after a lineup "
        "change is a fresh spawn of the same agent type, given the round-1 findings; "
        "first re-read the routing table of the current lineup_generation: if that "
        "author's cell is now same-family or names the other reviewer, follow the "
        "current table.",
        "- `/model`: press `s` (this session only). Enter saves the model into the user's "
        "global settings, which plain `claude` then inherits.",
    ]
    # Admission and qualification are current observations, not scope
    # authority. A new diagnostic or badge must never change a running
    # session's expected files, hashes, fence or recorded agent selector.
    warnings = [finding for finding in lineup.warnings if finding.code not in profile.TRANSIENT_WARNING_CODES]
    notices = [finding for finding in lineup.notices if finding.code not in profile.TRANSIENT_WARNING_CODES]
    if warnings or notices:
        lines += ["", "## Checks"]
        lines += [f"- ! {finding.message}" for finding in warnings]
        lines += [f"- {finding.message}" for finding in notices]
    data = ("\n".join(lines) + "\n").encode("utf-8")
    if len(data) > LINEUP_MD_MAX_BYTES:
        raise ScopeError(
            f"lineup.md is {len(data)} bytes, over the {LINEUP_MD_MAX_BYTES}-byte limit"
        )
    return data


def lineup_gen_line(generation: int, lineup_md: bytes) -> str:
    """``lineup.gen`` content: ``"<N> <sha256(lineup.md)[:12]>\\n"``."""

    _check_generation(generation)
    return f"{generation} {strict_json.sha256_hex(lineup_md)[:12]}\n"


def lead_set_bytes(
    lineup: profile.ResolvedLineup, fence: Fence, context: compiler.LeadContext
) -> bytes:
    """``<scope>/lead-set.json``.

    Launch-time data: a live apply never rewrites it (it is the fence).
    """

    lead = lineup.lead.binding
    document = {
        "context": context.as_document(),
        "lead": {
            "display": lead.display,
            "effort": lead.effort,
            "family": lead.family,
            "key": lead.key,
            "selector": lead.selector,
        },
        "lead_class": lineup.lead_class,
        "lead_providers": None
        if lineup.lead_providers is None
        else sorted(lineup.lead_providers),
        "rows": [
            {
                "display": row.display,
                "effort": row.effort,
                "family": row.family,
                "key": row.key,
                "label": row.label,
                "provider": row.provider,
                "selector": row.selector,
                "source": row.source,
            }
            for row in fence.lead_set
        ],
        "version": 1,
    }
    return strict_json.canonical_file_bytes(document)


def _agent_file_v2_bytes(agent: profile.ResolvedAgent, prompt_bodies: Mapping[str, bytes]) -> bytes:
    """§3.1: ``name, description, model, effort[, isolation][, disallowedTools]``."""

    binding, role = agent.binding, agent.role
    if binding.effort == profile.ULTRACODE:
        raise ScopeError(
            f"agent {role.id!r}: ultracode is a lead-only effort and must never "
            "appear as an agent effort value"
        )
    body = prompt_bodies.get(role.id)
    if body is None:
        raise ScopeError(f"agent {role.id!r}: no prompt body in the catalog")
    lines = [
        "---",
        f"name: {role.id}",
        f"description: {_yaml_double_quoted(role.description + ' ' + SENTINEL_SUFFIX)}",
        f"model: {binding.selector}",
        f"effort: {binding.effort}",
    ]
    if role.isolation is not None:
        lines.append(f"isolation: {role.isolation}")
    if role.disallowed_tools:
        lines.append("disallowedTools: " + ", ".join(role.disallowed_tools))
    lines += ["---", ""]
    return ("\n".join(lines) + "\n").encode("utf-8") + bytes(body)


def _lifecycle_settings_v2(
    managed_id: str,
    hook_command: str,
    launch_epoch: int,
    *,
    gateway_base_url: str,
) -> dict[str, Any]:
    """§3.2: six protocol-3 hooks (no matcher) and the lifecycle env."""

    _check_session_id(managed_id)
    if not hook_command:
        raise ScopeError("lifecycle hook command is empty")
    if PurePosixPath(hook_command).name != HOOK_SHIM_V3_RELATIVE.name:
        raise ScopeError(
            "v2 scopes must use the protocol-3 hook shim bin/claude-multi-hook-3"
        )
    if not isinstance(launch_epoch, int) or isinstance(launch_epoch, bool) or launch_epoch < 0:
        raise ScopeError("lifecycle launch_epoch must be a non-negative integer")
    tail = (
        f"--managed-id {shlex.quote(managed_id)} --launch-epoch {launch_epoch} "
        f"--hook-protocol {HOOK_PROTOCOL}"
    )
    quoted = shlex.quote(hook_command)

    def entry(event: str) -> list[dict[str, Any]]:
        return [
            {
                "hooks": [
                    {
                        "type": "command",
                        "command": f"{quoted} session-event {event} {tail}",
                        "timeout": 5,
                    }
                ]
            }
        ]

    return {
        "env": {
            "ANTHROPIC_BASE_URL": gateway_base_url,
            "CLAUDE_CODE_RETRY_WATCHDOG": "1",
            "CLAUDE_MULTI_LAUNCH_EPOCH": str(launch_epoch),
            "CLAUDE_MULTI_MANAGED_ID": managed_id,
            "CLAUDE_MULTI_SESSION_ID": managed_id,
        },
        "hooks": {name: entry(event) for name, event in HOOK_EVENTS_V3},
    }


# The managed-session feedback-drafts policy
# travels in the scope env, a launch-time key (restaged from the live scope,
# so a toggle never drifts a running session). The real-binary proof is
# tests/test_scope_probe_client.FeedbackDraftsProbe. ``notify`` omits the key and
# never overrides the user's own choice.
FEEDBACK_ENV = "CLAUDE_CODE_SEND_FEEDBACK"
FEEDBACK_DRAFTS_VALUES = settings_mod.FEEDBACK_DRAFTS_VALUES


# The fast-mode disable. The process environment
# alone is not enough: Claude user/project/local settings ``env`` override
# it, so the flag settings (which win over those layers) state it as well.
FAST_MODE_ENV = "CLAUDE_CODE_DISABLE_FAST_MODE"


# Claude Code 2.1.284+ starts a session whose settings configure no
# permission mode in ``auto`` (2.1.281 started in ``default``; both
# measured). A managed launch compiles ``permissions.defaultMode:
# "default"`` into the flag settings ONLY when no layer the client reads
# configures one (``managed.permission_mode_configured``); a configured layer
# or an explicit ``--permission-mode`` wins. Decided at launch and resume;
# every other compile of a live scope keeps that scope's on-disk presence or
# absence (``live_default_mode``), so it never adds or removes the key.
PERMISSION_DEFAULT_MODE = "default"


def feedback_drafts_env(value: str) -> dict[str, str]:
    """The scope env entries of a ``claude_feedback_drafts`` value."""

    if value not in FEEDBACK_DRAFTS_VALUES:
        raise ScopeError(f"claude_feedback_drafts must be one of {', '.join(FEEDBACK_DRAFTS_VALUES)}")
    return {FEEDBACK_ENV: "false"} if value == "off" else {}


def compile_lineup_scope(
    lineup: profile.ResolvedLineup,
    cat: profile.LineupCatalog,
    eff: settings_mod.Effective,
    prompt_bodies: Mapping[str, bytes],
    meta: CatalogMeta,
    *,
    lineup_generation: int,
    managed_id: str | None = None,
    hook_command: str | None = None,
    launch_epoch: int = 0,
    token_helper_command: str | None = None,
    no_subagents: bool = False,
    worktree_available: bool = True,
    secret_denies: Sequence[str] = SECRET_PATH_DENIES,
    proxy_env: Mapping[str, str] | None = None,
    feedback_drafts: str = settings_mod.FEEDBACK_DRAFTS_DEFAULT,
    default_mode: str | None = None,
) -> ScopePlan:
    """Pure v2 scope plan (§3.1-§3.6). No effects; fail closed on every gap.

    ``feedback_drafts`` is the explicit feedback-draft policy input (the current
    ``preferences.json`` value; absent = ``off``).

    ``default_mode`` is the explicit permission-mode decision:
    :data:`PERMISSION_DEFAULT_MODE` compiles ``permissions.defaultMode``,
    None compiles nothing (a settings layer configures one, or a live scope
    without the key). Launch/resume decide it; other compiles pass the live
    scope's own presence (:func:`live_default_mode`).

    ``lineup`` must be resolved with the same ``eff`` (``profile.resolve(...,
    effective=eff)``); the compile re-asserts fence membership anyway.
    ``cat`` is the merged view for launch callers (``custom.merge_docs`` →
    ``LineupCatalog.from_docs``). ``worktree_available`` is the git seam
    (one ``git rev-parse`` at launch compile). ``lineup.log`` is never plan
    content (it lives under ``<state>/lineup-log/``).
    """

    generation = _check_generation(lineup_generation)
    view = line_view(cat, eff)
    fence = _compile_fence(lineup, cat, view, eff)
    percent = settings_mod.compaction_percent_for(eff, lineup.settings_overrides)
    try:
        context = compiler.lead_set_context(fence, percent, ceiling=profile.window_ceiling(eff))
    except compiler.CompilerError as exc:
        raise ScopeError(str(exc)) from exc

    # Every bound agent selector and the workflow default in the fence.
    gaps = frozenset(
        fence_gaps(
            fence.available_models,
            (agent.binding.selector for agent in lineup.agents.values()),
        )
    )
    if gaps:
        named = ", ".join(
            f"{rid} ({agent.binding.selector!r})"
            for rid, agent in lineup.agents.items()
            if agent.binding.selector in gaps
        )
        raise ScopeError(
            f"bound agent selectors outside the session fence: {named} "
            "(line unavailable: provider disabled or route unusable)"
        )
    workflow_default = _workflow_default(cat, view, eff, context.policy)
    if workflow_default is not None and fence_gaps(fence.available_models, [workflow_default]):
        raise ScopeError(
            f"{_WORKFLOW_FIELD}: {workflow_default!r} is outside the session fence"
        )

    agent_files: dict[str, bytes] = {}
    for rid, agent in lineup.agents.items():
        agent_files[str(_AGENT_DIR_RELPATH / f"{rid}.md")] = _agent_file_v2_bytes(
            agent, prompt_bodies
        )

    try:
        family_env = compiler.family_default_env(
            {line.key: dict(line.entry) for line in view.lines}, dict(cat.providers)
        )
    except compiler.CompilerError as exc:
        raise ScopeError(str(exc)) from exc
    env: dict[str, str] = dict(family_env)
    env.update(proxy_env or {})
    # Flag settings win over user/project env and survive takeover.
    env["CLAUDE_CODE_AUTO_COMPACT_WINDOW"] = str(context.window)
    env["CLAUDE_AUTOCOMPACT_PCT_OVERRIDE"] = str(context.percent)
    if context.scalar is not None:
        env["CLAUDE_CODE_MAX_CONTEXT_TOKENS"] = str(context.scalar)
    if eff.explore_inherit_cap_disabled:
        env["CLAUDE_CODE_DISABLE_EXPLORE_INHERIT_CAP"] = "1"
    if workflow_default is not None:
        env["CLAUDE_CODE_SUBAGENT_MODEL"] = workflow_default
    env.update(feedback_drafts_env(feedback_drafts))
    env[FAST_MODE_ENV] = "1"

    _, denies = compiler.compile_native_policy(
        dict(lineup.native_agents), meta.generic_agent_aliases
    )
    settings: dict[str, Any] = dict(meta.base_settings)
    # --no-subagents also turns workflows off (a workflow agent() without
    # an agentType is not stopped by the Agent deny).
    settings["disableWorkflows"] = lineup.workflows == "off" or no_subagents
    # The named skill denies join (never replace) the native-agent
    # and secret denies, in every lineup (direct and --no-subagents included).
    settings["permissions"] = {
        "deny": [*(["Agent"] if no_subagents else denies), *MANAGED_SKILL_DENIES, *secret_denies]
    }
    if default_mode is not None:
        if default_mode != PERMISSION_DEFAULT_MODE:
            raise ScopeError(f"the compiled permission default mode must be {PERMISSION_DEFAULT_MODE!r}")
        settings["permissions"]["defaultMode"] = default_mode
    settings["availableModels"] = list(fence.available_models)
    settings["model"] = lineup.lead.binding.selector
    settings["modelPicker"] = {
        "options": [
            {"description": f"claude-multi · {row.key}", "label": row.label, "model": row.selector}
            for row in fence.lead_set
        ],
        "replaceBuiltInOptions": True,
    }
    settings["autoCompactEnabled"] = True
    # Keep the model fence and lifecycle hooks enabled.
    settings["disableAllHooks"] = False
    settings["worktree"] = {"baseRef": "head"}
    if managed_id is not None or hook_command is not None:
        if managed_id is None or hook_command is None:
            raise ScopeError("managed_id and hook_command must be supplied together")
        lifecycle = _lifecycle_settings_v2(
            managed_id, hook_command, launch_epoch, gateway_base_url=meta.gateway_base_url
        )
        env.update(lifecycle["env"])
        settings["hooks"] = lifecycle["hooks"]
        if token_helper_command:
            settings["apiKeyHelper"] = token_helper_command
    settings["env"] = env
    unknown = sorted(set(settings) - COMPILED_SETTINGS_KEYS)
    if unknown:
        raise ScopeError(
            f"compiled settings carry keys outside the closed allowlist: {unknown}"
        )
    missing = [key for key in _BASE_WORKFLOW_KEYS if key not in settings]
    if missing:
        raise ScopeError(
            f"package base settings do not supply required workflow keys {missing}"
        )

    lineup_md = lineup_md_bytes(
        lineup,
        fence,
        eff,
        generation=generation,
        no_subagents=no_subagents,
        default_row_model=family_env.get(_OPUS_DEFAULT_ENV),
        workflow_default=workflow_default,
        worktree_available=worktree_available,
    )
    other_files = {
        LINEUP_MD: lineup_md,
        LINEUP_GEN: lineup_gen_line(generation, lineup_md).encode("utf-8"),
        LEAD_SET_JSON: lead_set_bytes(lineup, fence, context),
        SKILL_RELPATH: SKILL_MD_BYTES,
    }
    return ScopePlan(agent_files=agent_files, settings=settings, other_files=other_files)


def find_skill_collisions(
    cwd: Path | str,
    add_dirs: Iterable[Path | str],
    names: Iterable[str] = frozenset({"cm"}),
    *,
    user_skills_dir: Path | None = None,
) -> list[tuple[Path, str]]:
    """Project/add-dir/user skills that share a name with a scope skill (read-only).

    Walks ``.claude/skills/<name>/SKILL.md`` from ``cwd`` up to the git root
    (as :func:`find_cm_collisions`), under each passthrough ``--add-dir`` and
    ``user_skills_dir/<name>/SKILL.md`` when given. Unreadable paths are
    skipped (doctor reports them as Attention).
    """

    wanted = sorted(set(names))
    found: list[tuple[Path, str]] = []
    seen: set[Path] = set()

    def check(skills_dir: Path) -> None:
        for name in wanted:
            candidate = skills_dir / name / "SKILL.md"
            try:
                if not candidate.is_file():
                    continue
                key = candidate.resolve()
            except OSError:
                continue
            if key in seen:
                continue
            seen.add(key)
            found.append((candidate, name))

    try:
        start = Path(cwd).resolve()
    except OSError:
        start = Path(cwd)
    for ancestor in (start, *start.parents):
        check(ancestor / ".claude" / "skills")
        try:
            if (ancestor / ".git").exists():
                break
        except OSError:
            break
    for add_dir in add_dirs:
        check(Path(add_dir) / ".claude" / "skills")
    if user_skills_dir is not None:
        check(Path(user_skills_dir))
    return sorted(found, key=lambda item: (str(item[0]), item[1]))


def plan_hash(plan: ScopePlan) -> str:
    """Content hash of a plan: canonical settings plus per-file digests."""

    manifest: dict[str, Any] = {
        "agent_files": {
            relpath: "sha256:" + strict_json.sha256_hex(data)
            for relpath, data in sorted(plan.agent_files.items())
        },
        "settings": plan.settings,
    }
    # Only when present, so every legacy plan hash is unchanged.
    if plan.other_files:
        manifest["other_files"] = {
            relpath: "sha256:" + strict_json.sha256_hex(data)
            for relpath, data in sorted(plan.other_files.items())
        }
    return strict_json.bundle_digest(manifest)


def scope_dir(state_root: Path | str, session_id: str) -> Path:
    """The live scope directory for a session."""

    return Path(state_root) / "scopes" / _check_session_id(session_id)


def _fsync_directory(path: Path) -> None:
    descriptor = os.open(path, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def _remove_tree(path: Path) -> None:
    """Remove a scope tree; refuse symlinks and non-directories."""

    info = os.lstat(path)
    if stat.S_ISLNK(info.st_mode):
        raise state.StateError(errno.ELOOP, f"scope path {path} is a symlink")
    if not stat.S_ISDIR(info.st_mode):
        raise state.StateError(
            errno.ENOTDIR, f"scope path {path} is not a directory"
        )
    shutil.rmtree(path)


def _check_relpath(relpath: str) -> PurePosixPath:
    candidate = PurePosixPath(relpath)
    if candidate.is_absolute() or ".." in candidate.parts:
        raise ScopeError(f"unsafe scope-relative path {relpath!r}")
    return candidate


# The compiled settings file every scope carries (never an agent/other key).
SETTINGS_RELPATH = "settings.json"


def _plan_files(plan: ScopePlan) -> dict[str, bytes]:
    """Every scope file of a plan by normalised relpath.

    ``agent_files``, ``other_files`` and ``settings.json`` must be disjoint
    after normalisation (``./a`` is ``a``), and no file path may also be a
    directory of another file; any overlap is a ``ScopeError`` before any
    effect. Legacy plans (no ``other_files``) map to exactly the files
    ``write_scope`` always wrote.
    """

    files: dict[str, bytes] = {}
    for group in (plan.agent_files, plan.other_files):
        for relpath, data in group.items():
            relative = _check_relpath(relpath)
            key = relative.as_posix()
            if not relative.parts:
                raise ScopeError(f"empty scope-relative path {relpath!r}")
            if key == SETTINGS_RELPATH or key in files:
                raise ScopeError(
                    f"scope plan names {key!r} more than once (agent files, other "
                    "files and settings.json must be disjoint)"
                )
            if not isinstance(data, bytes):
                raise ScopeError(f"scope file {key!r} content must be bytes")
            files[key] = data
    files[SETTINGS_RELPATH] = strict_json.canonical_file_bytes(plan.settings)
    directories = {
        parent.as_posix()
        for key in files
        for parent in PurePosixPath(key).parents
        if parent.parts
    }
    clash = sorted(directories & set(files))
    if clash:
        raise ScopeError(f"scope plan path {clash[0]!r} is both a file and a directory")
    return files


def stage_plan(state_root: Path | str, session_id: str, plan: ScopePlan) -> Path:
    """Stage ``scopes/.<uuid>.new/`` from a plan without touching the live scope.

    Validates every relpath first (:func:`_plan_files`), then removes a stale
    staging directory, writes every agent and other file with
    ``state.atomic_write`` (0600) under ``state.ensure_private_dir`` (0700)
    directories, and ``settings.json`` last. Returns the staging path; the
    swap is the caller's (``write_scope`` here, converge's swap).

    The lineup log is not scope content (it lives at
    ``<state>/lineup-log/<managed_id>.log``), so no rewrite ever has to carry
    it and an append can never race the live-tree removal.
    """

    _check_session_id(session_id)
    files = _plan_files(plan)
    scopes_root = state.ensure_private_dir(Path(state_root) / "scopes")
    staging = scopes_root / f".{session_id}.new"
    if os.path.lexists(staging):
        _remove_tree(staging)
    state.ensure_private_dir(staging)
    settings_bytes = files.pop(SETTINGS_RELPATH)
    for relpath, data in sorted(files.items()):
        target = staging.joinpath(*PurePosixPath(relpath).parts)
        state.ensure_private_dir(target.parent)
        state.atomic_write(target, data)
    state.atomic_write(staging / SETTINGS_RELPATH, settings_bytes)
    return staging


def write_scope(state_root: Path | str, session_id: str, plan: ScopePlan) -> Path:
    """Stage the plan into ``scopes/.<uuid>.new/`` and rename it into place.

    Per-file writes use ``state.atomic_write`` (mode 0600); directories are
    mode 0700 via ``state.ensure_private_dir``. A stale staging directory from
    an interrupted write is removed first. If a live scope already exists it
    is removed just before the rename; the record remains the authority and
    the scope is re-derivable from record+catalog across that window. The
    ``scopes/`` parent is fsynced after the rename.
    """

    staging = stage_plan(state_root, session_id, plan)
    scopes_root = staging.parent
    live = scopes_root / session_id
    if os.path.lexists(live):
        _remove_tree(live)
    os.rename(staging, live)
    _fsync_directory(scopes_root)
    return live


def _check_real_dir(path: Path, what: str) -> None:
    """Fail closed when an existing scope path is a symlink or not a directory."""

    if not os.path.lexists(path):
        return
    info = os.lstat(path)
    if stat.S_ISLNK(info.st_mode):
        raise ScopeError(f"{what} scope path {path} is a symlink")
    if not stat.S_ISDIR(info.st_mode):
        raise ScopeError(f"{what} scope path {path} is not a directory")


def swap_scope(
    state_root: Path | str,
    session_id: str,
    plan: ScopePlan,
    *,
    dir_fsync: Callable[[Path], None] | None = None,
) -> bool:
    """Replace the live scope through the ``.prev``/``.new`` swap.

    Stages ``.<id>.new``
    (:func:`stage_plan`), removes a superseded ``.<id>.prev``, renames the
    live scope to ``.prev`` (when one exists) and ``.new`` to live, fsyncing
    ``scopes/`` after each step. A rename failure is undone exactly (live
    back from ``.prev``, staging removed) and raised as ``ScopeError``; when
    the undo itself fails the error names ``doctor --repair``. Returns
    whether a live scope existed (its bytes are now ``.prev``, the one
    rollback source :func:`restore_prev_scope` uses).
    """

    sync = dir_fsync if dir_fsync is not None else _fsync_directory
    _check_session_id(session_id)
    scopes_root = state.ensure_private_dir(Path(state_root) / "scopes")
    live = scopes_root / session_id
    prev = scopes_root / f".{session_id}.prev"
    _check_real_dir(live, "live")
    _check_real_dir(prev, "previous-generation")
    staging = stage_plan(state_root, session_id, plan)
    had_live = os.path.lexists(live)
    live_moved = False
    staged_in = False
    try:
        if had_live and os.path.lexists(prev):
            # Superseded by the live scope about to move there. Without a live
            # scope a `.prev` is the only copy of the prior scope (a crash
            # between the renames) and is left alone.
            _remove_tree(prev)
            sync(scopes_root)
        if had_live:
            os.rename(live, prev)
            live_moved = True
            sync(scopes_root)
        os.rename(staging, live)
        staged_in = True
        sync(scopes_root)
    except OSError as exc:
        try:
            if staged_in and os.path.lexists(live):
                _remove_tree(live)
            if live_moved and os.path.lexists(prev):
                os.rename(prev, live)
            if os.path.lexists(staging):
                _remove_tree(staging)
            sync(scopes_root)
        except OSError as rollback_exc:
            raise ScopeError(
                f"scope swap failed and rollback could not be confirmed: {exc}; "
                f"rollback: {rollback_exc}; run `claude-multi doctor --repair {session_id}`"
            ) from exc
        raise ScopeError(f"scope swap failed: {exc}; the prior scope was restored") from exc
    return had_live


def restore_prev_scope(
    state_root: Path | str,
    session_id: str,
    *,
    dir_fsync: Callable[[Path], None] | None = None,
) -> None:
    """Put ``.<id>.prev`` back as the live scope (a launch that never ran).

    Removes the live scope (if any), then renames ``.prev`` to live and
    fsyncs ``scopes/``. ``ScopeError`` when ``.prev`` is missing.
    """

    sync = dir_fsync if dir_fsync is not None else _fsync_directory
    _check_session_id(session_id)
    scopes_root = state.ensure_private_dir(Path(state_root) / "scopes")
    live = scopes_root / session_id
    prev = scopes_root / f".{session_id}.prev"
    _check_real_dir(live, "live")
    _check_real_dir(prev, "previous-generation")
    if not os.path.lexists(prev):
        raise ScopeError(f"no previous scope to restore for {session_id}")
    if os.path.lexists(live):
        _remove_tree(live)
    os.rename(prev, live)
    sync(scopes_root)


def remove_live_scope(state_root: Path | str, session_id: str) -> bool:
    """Remove only the live scope and a stale ``.new`` (never ``.prev``). Idempotent."""

    _check_session_id(session_id)
    scopes_root = state.ensure_private_dir(Path(state_root) / "scopes")
    removed = False
    for candidate in (scopes_root / session_id, scopes_root / f".{session_id}.new"):
        if os.path.lexists(candidate):
            _remove_tree(candidate)
            removed = True
    if removed:
        _fsync_directory(scopes_root)
    return removed


def live_drift(live: Path, plan: ScopePlan) -> list[str]:
    """Why the on-disk live scope differs from the expected plan (empty == match).

    ``transition._live_drift`` delegates here. Expected files are the
    plan's agent files, other files (the v2 lineup files, ``lead-set.json``
    and the ``/cm`` skill) and ``settings.json``; every expected file must be a regular owner file of
    mode 0600 with the exact bytes, every directory owner 0700, and anything
    else in the tree is drift. The lineup log lives outside the scope, so a
    ``lineup.log`` inside it is an unexpected file like any other. Legacy
    plans report their own drift unchanged.
    """

    expected = _plan_files(plan)
    expected_dirs: set[str] = set()
    for relpath in expected:
        parent = Path(relpath).parent
        while parent != Path("."):
            expected_dirs.add(parent.as_posix())
            parent = parent.parent

    problems: list[str] = []
    seen: set[str] = set()
    owner = os.geteuid()
    root_info = os.lstat(live)
    if root_info.st_uid != owner:
        problems.append("scope root is not owner-controlled")
    if stat.S_IMODE(root_info.st_mode) != 0o700:
        problems.append("scope root mode is not 0700")

    for dirpath, dirnames, filenames in os.walk(live, topdown=True, followlinks=False):
        directory = Path(dirpath)
        for dirname in sorted(list(dirnames)):
            full = directory / dirname
            relpath = full.relative_to(live).as_posix()
            try:
                info = os.lstat(full)
            except OSError as exc:
                problems.append(f"cannot inspect directory {relpath}: {exc}")
                dirnames.remove(dirname)
                continue
            if stat.S_ISLNK(info.st_mode):
                problems.append(f"directory {relpath} is a symlink")
                dirnames.remove(dirname)
                continue
            if not stat.S_ISDIR(info.st_mode):
                problems.append(f"{relpath} is not a directory")
                dirnames.remove(dirname)
                continue
            if relpath not in expected_dirs:
                problems.append(f"unexpected directory {relpath}")
                dirnames.remove(dirname)
                continue
            unsafe = False
            if info.st_uid != owner:
                problems.append(f"directory {relpath} is not owner-controlled")
                unsafe = True
            if stat.S_IMODE(info.st_mode) != 0o700:
                problems.append(f"directory {relpath} mode is not 0700")
                unsafe = True
            if unsafe:
                dirnames.remove(dirname)

        for filename in sorted(filenames):
            full = directory / filename
            relpath = full.relative_to(live).as_posix()
            seen.add(relpath)
            data = expected.get(relpath)
            if data is None:
                problems.append(f"unexpected file {relpath}")
                continue
            try:
                info = os.lstat(full)
            except OSError as exc:
                problems.append(f"cannot inspect file {relpath}: {exc}")
                continue
            if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
                problems.append(f"{relpath} is not a regular file")
                continue
            if info.st_uid != owner:
                problems.append(f"{relpath} is not owner-controlled")
                continue
            if stat.S_IMODE(info.st_mode) != 0o600:
                problems.append(f"{relpath} mode is not 0600")
                continue
            try:
                actual = full.read_bytes()
            except OSError as exc:
                problems.append(f"cannot read file {relpath}: {exc}")
                continue
            if actual != data:
                problems.append(f"{relpath} content differs")
    for relpath in sorted(set(expected) - seen):
        problems.append(f"missing file {relpath}")
    return problems


_SKILL_POLICY_DRIFT_LINES = frozenset(
    f"{relpath} content differs" for relpath in (SETTINGS_RELPATH, SKILL_RELPATH)
)


def _skill_denies(settings: Mapping[str, Any]) -> tuple[Any, list[Any]] | None:
    """``(settings without the named skill denies, those denies in order)``;
    None when ``permissions.deny`` is not a list of strings (damage, never
    skill-policy drift)."""

    permissions = settings.get("permissions")
    if not isinstance(permissions, Mapping) or not isinstance(permissions.get("deny"), list):
        return None
    deny = permissions["deny"]
    if not all(isinstance(entry, str) for entry in deny):
        return None
    named = set(MANAGED_SKILL_DENIES)
    rest = {**settings, "permissions": {**permissions, "deny": [e for e in deny if e not in named]}}
    return rest, [entry for entry in deny if entry in named]


def _without_default_mode(settings: Mapping[str, Any]) -> Any:
    permissions = settings.get("permissions")
    if not isinstance(permissions, Mapping) or "defaultMode" not in permissions:
        return settings
    return {**settings, "permissions": {k: v for k, v in permissions.items() if k != "defaultMode"}}


def _default_mode_of(settings: Any) -> tuple[bool, Any]:
    permissions = settings.get("permissions") if isinstance(settings, Mapping) else None
    if not isinstance(permissions, Mapping) or "defaultMode" not in permissions:
        return False, None
    return True, permissions["defaultMode"]


def live_default_mode(live: Path | None) -> str | None:
    """The permission-mode decision input of a compile of a LIVE
    scope: its own on-disk presence of ``permissions.defaultMode``
    (:data:`PERMISSION_DEFAULT_MODE` when present, None when absent or the
    scope is unreadable). Never re-decided from the current settings layers,
    so doctor, converge, ``--repair-all --include-live``, ``/cm`` and
    ``lineup set`` never add or remove the key. Read-only; never reports
    the value."""

    if live is None:
        return None
    # The tolerant reader: a permission-bits defect that
    # invalidates the private read must not erase the launch's decision
    # while repair rewrites the file.
    present, _value = _default_mode_of(managed.read_settings(Path(live) / SETTINGS_RELPATH))
    return PERMISSION_DEFAULT_MODE if present else None


def _live_settings(live: Path) -> Any:
    try:
        return strict_json.loads(state.read_private(Path(live) / SETTINGS_RELPATH))
    except (OSError, state.StateError, strict_json.StrictJSONError):
        return None


def default_mode_differs(live: Path, plan: ScopePlan) -> bool:
    """The live ``settings.json`` states another
    ``permissions.defaultMode`` (presence or value) than ``plan``."""

    disk = _live_settings(live)
    return isinstance(disk, dict) and _default_mode_of(disk) != _default_mode_of(plan.settings)


def default_mode_drift(live: Path, plan: ScopePlan, drifted: Sequence[str]) -> bool:
    """True when the ONLY drift of a live scope is
    ``permissions.defaultMode`` (presence or value) in ``settings.json``:
    lazy state ("applies at the next resume"), never BLOCK. Read-only."""

    if list(drifted) != [f"{SETTINGS_RELPATH} content differs"]:
        return False
    disk = _live_settings(live)
    if not isinstance(disk, dict) or _default_mode_of(disk) == _default_mode_of(plan.settings):
        return False
    return _without_default_mode(disk) == _without_default_mode(plan.settings)


def skill_policy_drift(live: Path, plan: ScopePlan, drifted: Sequence[str]) -> bool:
    """True when the ONLY drift of a live scope
    (``live_drift`` lines) is the managed skill policy of another release —
    lazy state that resume or ``doctor --repair`` resolves.

    ``settings.json`` may differ from ``plan`` only by the named skill
    denies, all of them or none (a scope without the deny, or one with it
    under a rollback compile); the ``/cm`` skill may hold a previous release's exact
    bytes. A partial deny set, any other permissions change or any other
    file is not: doctor keeps it BLOCK. Read-only."""

    if not drifted or any(line not in _SKILL_POLICY_DRIFT_LINES for line in drifted):
        return False
    if f"{SETTINGS_RELPATH} content differs" in drifted:
        try:
            disk = strict_json.loads(state.read_private(Path(live) / SETTINGS_RELPATH))
        except (OSError, state.StateError, strict_json.StrictJSONError):
            return False
        on_disk = _skill_denies(disk) if isinstance(disk, dict) else None
        expected = _skill_denies(plan.settings)
        # A permission default-mode difference alongside is lazy too.
        if (on_disk is None or expected is None
                or _without_default_mode(on_disk[0]) != _without_default_mode(expected[0])):
            return False
        if on_disk[1] not in ([], list(MANAGED_SKILL_DENIES)):
            return False
        if (on_disk[1] == expected[1]
                and f"{SKILL_RELPATH} content differs" not in drifted):
            return False  # a default-mode-only delta is default_mode_drift
    if f"{SKILL_RELPATH} content differs" in drifted:
        try:
            skill = state.read_private(Path(live) / SKILL_RELPATH)
        except (OSError, state.StateError):
            return False
        known = (*PREVIOUS_SKILL_MD_BYTES, SKILL_MD_BYTES)
        if skill not in known or plan.other_files.get(SKILL_RELPATH) not in known:
            return False
    return True


def read_disk_plan(live: Path, expected: ScopePlan) -> ScopePlan | None:
    """Read an on-disk scope as a plan for ``plan_hash`` comparison. Read-only.

    Every ``.claude/agents/*.md`` file, each of ``expected.other_files``'
    relpaths (a missing one is omitted, so the hash differs) and
    ``settings.json``, all through ``state.read_private`` (regular owner file, no group/other
    bits, symlinks refused). Returns None when any surface is unreadable: a
    scope that cannot be read cannot be verified, and the caller reports a
    mismatch.
    """

    live = Path(live)
    agent_files: dict[str, bytes] = {}
    agents_dir = live.joinpath(*_AGENT_DIR_RELPATH.parts)
    try:
        entries = sorted(agents_dir.iterdir())
    except OSError:
        entries = []
    for entry in entries:
        try:
            if not entry.is_file() or entry.suffix != ".md":
                continue
            agent_files[f"{_AGENT_DIR_RELPATH.as_posix()}/{entry.name}"] = state.read_private(entry)
        except (OSError, state.StateError):
            return None
    other_files: dict[str, bytes] = {}
    for relpath in sorted(expected.other_files):
        path = live.joinpath(*_check_relpath(relpath).parts)
        try:
            other_files[relpath] = state.read_private(path)
        except state.StateError as exc:
            if exc.errno == errno.ENOENT and not os.path.lexists(path):
                continue
            return None
        except OSError:
            return None
    try:
        settings = strict_json.loads(state.read_private(live / SETTINGS_RELPATH))
    except (OSError, state.StateError, strict_json.StrictJSONError):
        return None
    if not isinstance(settings, dict):
        return None
    return ScopePlan(agent_files=agent_files, settings=settings, other_files=other_files)


def remove_scope(state_root: Path | str, session_id: str) -> bool:
    """Remove a session's live scope and any stale staging dir. Idempotent."""

    _check_session_id(session_id)
    # Validate the scopes PARENT before any destructive work beneath it: a
    # symlinked ancestor must fail closed here, never be followed.
    scopes_root = state.ensure_private_dir(Path(state_root) / "scopes")
    removed = False
    for candidate in (
        scopes_root / session_id,
        scopes_root / f".{session_id}.new",
        scopes_root / f".{session_id}.prev",
    ):
        if os.path.lexists(candidate):
            _remove_tree(candidate)
            removed = True
    if removed:
        _fsync_directory(scopes_root)
    return removed


def _frontmatter_name(path: Path) -> str | None:
    """Line-wise frontmatter ``name:`` extraction (no YAML dependency).

    Returns None for files without a frontmatter block or without a name;
    unreadable files are skipped by the caller (they cannot shadow a loaded
    definition for the same user). YAML inline comments are ignored unless
    they occur inside a quoted scalar.
    """

    try:
        with open(path, "rb") as handle:
            raw = handle.read(65536)
    except OSError:
        return None
    text = raw.decode("utf-8", errors="replace")
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    name: str | None = None
    for line in lines[1:]:
        stripped = line.strip()
        if stripped == "---":
            return name
        if stripped.startswith("name:") or stripped.startswith("name :"):
            value = stripped.split(":", 1)[1].strip()
            quote: str | None = None
            escaped = False
            for index, character in enumerate(value):
                if quote == '"':
                    if escaped:
                        escaped = False
                    elif character == "\\":
                        escaped = True
                    elif character == quote:
                        quote = None
                elif quote == "'":
                    if character == quote:
                        quote = None
                elif character in "\"'":
                    quote = character
                elif character == "#" and (
                    index == 0 or value[index - 1].isspace()
                ):
                    value = value[:index].rstrip()
                    break
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            name = value
    return None


def _scan_agents_dir(
    directory: Path, generated_names: frozenset[str]
) -> list[tuple[Path, str]]:
    """Recursively scan one native agent directory, skipping unreadable paths."""

    collisions: list[tuple[Path, str]] = []
    for root, directories, filenames in os.walk(
        directory, topdown=True, onerror=lambda _error: None, followlinks=False
    ):
        directories.sort()
        for filename in sorted(filenames):
            entry = Path(root) / filename
            try:
                if not entry.is_file() or entry.suffix != ".md":
                    continue
            except OSError:
                continue
            name = _frontmatter_name(entry)
            if name is not None and name in generated_names:
                collisions.append((entry, name))
    return collisions


def find_cm_collisions(
    cwd: Path | str,
    add_dirs: Iterable[Path | str],
    generated_names: frozenset[str] | set[str],
    *,
    managed_agents_dir: Path | None = DEFAULT_MANAGED_AGENTS_DIR,
) -> list[tuple[Path, str]]:
    """Exact ``cm-*`` name collisions outside the managed scope (fail closed).

    Scans (a) every ``.claude/agents/`` directory from ``cwd`` up to and
    including the git root (first ancestor containing ``.git``) or the
    filesystem root, (b) ``.claude/agents/`` under each passthrough
    ``--add-dir``, and (c) the managed settings agents directory when it
    exists and is readable. ``add_dirs`` must be the user passthrough dirs
    only — never the session's own scope dir. Returns a deterministic sorted
    list of ``(offending file, colliding name)``; empty means clean. Exposed
    for Doctor's collision check as well as the durable launch gate.
    """

    names = frozenset(generated_names)
    collisions: list[tuple[Path, str]] = []
    seen: set[Path] = set()

    def scan(directory: Path) -> None:
        try:
            key = directory.resolve()
        except OSError:
            key = directory
        if key in seen:
            return
        seen.add(key)
        collisions.extend(_scan_agents_dir(directory, names))

    start = Path(cwd).resolve()
    for ancestor in (start, *start.parents):
        candidate = ancestor / ".claude" / "agents"
        if candidate.is_dir():
            scan(candidate)
        if (ancestor / ".git").exists():
            break
    for add_dir in add_dirs:
        candidate = Path(add_dir) / ".claude" / "agents"
        if candidate.is_dir():
            scan(candidate)
    if managed_agents_dir is not None and managed_agents_dir.is_dir():
        scan(managed_agents_dir)
    return sorted(collisions, key=lambda item: (str(item[0]), item[1]))
