# The named inventory of the
# pinned client's bundled skills that launch agents outside the bound cm
# lineup or edit files, settings or repository state. Every managed session
# compiles ``Skill(<name>)`` into ``permissions.deny`` for the lead and every
# cm-* subagent (session settings, not agent frontmatter: S13 showed a
# frontmatter ``Skill(<name>)`` drops the whole tool). The deny blocks model
# invocation only; an operator-typed slash command still runs, and plain
# ``claude`` is untouched. The third field is the S14 class at the pin
# (``test_managed_skill_policy`` re-proves it against the real binary):
#   model   model-invocable without a prompt: newly denied;
#   ask     model-invocable after a permission approval: newly denied;
#   user    upstream ``disable-model-invocation``: already refused upstream,
#           the deny is defence in depth and never counted as proof;
#   absent  not registered at the pin (feature-gated): named in advance.
# Aliases resolve before the permission check (``review`` →
# ``code-review``, ``checkup`` → ``doctor``, ``routines`` → ``schedule``),
# and a subcommand is an argument of its skill (``/code-review ultra``).
# Not a universal skill sandbox: arbitrary user or plugin skills are not
