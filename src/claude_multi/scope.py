"""Durable per-session scopes for claude-multi.

A scope is the per-session directory ``<state_root>/scopes/<uuid>/`` holding
every generated, policy-relevant file for one managed session::

    scopes/<uuid>/
    ├── .claude/agents/cm-<role>.md      # one per bound agent id
    ├── .claude/skills/cm/SKILL.md       # the /cm skill
    ├── settings.json                    # compiled session settings
    └── lineup.md, lineup.gen, lead-set.json

:func:`compile_lineup_scope` is pure: it maps (resolved
lineup, v2 catalog data, Settings, prompt bodies, catalog metadata) to a
plan of file bytes plus the compiled settings document: agent files by role
id, the split fence (lead set, agent set, fallback-only set) with
``modelPicker`` and ``lead-set.json``, ``lineup.md``/``lineup.gen``, the
``/cm`` skill and protocol-3 hooks. It reads only v2 catalog data. The
effects are :func:`stage_plan` (stage into the sibling ``scopes/.<uuid>.new/``
with per-file ``state.atomic_write``), :func:`swap_scope` (the
``.new``/``.prev`` swap every launch and converge uses), :func:`write_scope`
(stage + rename, probes and tests only), :func:`live_drift` and
:func:`read_disk_plan`. Scope content is a pure function of (record,
installed catalog); a lost or drifted scope is always re-derivable. The
session's lineup log is not scope content: it lives at
``<state>/lineup-log/<managed_id>.log`` (``lineup_log.py``).

The exact-``cm-*`` collision gate (:func:`find_cm_collisions`) scans project
agent directories, passthrough ``--add-dir`` agent directories, and the
managed settings agents directory for agent files whose frontmatter ``name``
exactly equals one of the session's generated variant IDs. A collision would
silently shadow a guaranteed definition (closest-to-cwd precedence), so the
launcher fails closed naming the offending file. The scanner is line-wise:
no YAML dependency, tolerant of unreadable files (a file the session user
cannot read cannot shadow anything either).
"""

