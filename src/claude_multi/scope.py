def _under_wsl(environ: Mapping[str, str]) -> bool:
    import sys

    from claude_multi.platform import mounts

    return sys.platform.startswith("linux") and mounts.wsl(environ) is not None


def secret_path_denies(environ: Mapping[str, str], *, wsl: bool | None = None) -> tuple[str, ...]:
    """Stable HOME-relative rules, or Claude's // absolute-path syntax.

    Besides the fixed rules: under WSL (``wsl``; None detects it) the
    Windows side's Claude configuration and secrets
    (:data:`WSL_SECRET_PATH_DENIES`), a moved Anthropic config folder, and
    every credential location (``secret_store.credential_locations``) the
    folder rules do not cover — in practice an API-key file the environment
    or the key-file pointer selects outside claude-multi's own folder (the
    folder rules already cover the default file and the account sign-ins) —
    denied to Read and Edit wherever it is."""
    return tuple(rule for rule, _cause in _secret_path_rules(environ, wsl=wsl))


def secret_deny_causes(environ: Mapping[str, str], *, wsl: bool | None = None) -> tuple[tuple[str, str], ...]:
    """``(rule, cause)`` for every compiled secret deny the launch
    environment adds to the fixed ones: what doctor names when a scope's
    denies differ only because it was compiled from another shell (a key
    file an environment variable selects, a moved config folder, WSL)."""

    return tuple((rule, cause) for rule, cause in _secret_path_rules(environ, wsl=wsl) if cause)


def _secret_path_rules(environ: Mapping[str, str], *, wsl: bool | None) -> list[tuple[str, str]]:
    rules: list[tuple[str, str]] = [(rule, "") for rule in SECRET_PATH_DENIES]
    if wsl if wsl is not None else _under_wsl(environ):
        rules += [(rule, "WSL: the Windows side's Claude configuration") for rule in WSL_SECRET_PATH_DENIES]
    home = Path(environ.get("HOME", "/nonexistent"))
    default = home / ".config/anthropic"

    def shown(path: Path) -> str:
        try:
            return "~/" + str(path.relative_to(home))
        except ValueError:
            return "/" + str(path)

    def add(rule: str, cause: str) -> None:
        if all(rule != existing for existing, _cause in rules):
            rules.append((rule, cause))

    candidates = [("ANTHROPIC_CONFIG_DIR", environ.get("ANTHROPIC_CONFIG_DIR"))]
    if environ.get("XDG_CONFIG_HOME"):
        candidates.append(("XDG_CONFIG_HOME", str(Path(environ["XDG_CONFIG_HOME"]) / "anthropic")))
    for variable, value in candidates:
        if not value or not Path(value).is_absolute():
            continue
        path = Path(os.path.normpath(value))
        if path == default:
            continue
        add(f"Read({shown(path).rstrip('/')}/**)", f"{variable} moves the Anthropic config folder")
    from claude_multi import secret_store

    def covered(path: Path) -> bool:
        for rule, _cause in rules:
            if not rule.startswith("Read(") or not rule.endswith("/**)"):
                continue
            spec = rule[len("Read("):-len("/**)")]
            base = home / spec[2:] if spec.startswith("~/") else Path(spec[1:]) if spec.startswith("//") else None
            if base is not None and (path == base or base in path.parents):
                return True
        return False

    # Every credential location the folder rules do not cover yet (in
    # practice a key file the environment or the pointer selects outside
    # claude-multi's own folder).
    env = {**environ, "HOME": str(home)}
    pointed = secret_store.pointer_key_files(env)
    for path in secret_store.credential_locations(env):
        if covered(path):
            continue
        cause = ("the key-file pointer (secret-file.json) selects a key file outside ~/.config/claude-multi"
                 if path in pointed else
                 f"{secret_store.SECRET_ENV_OVERRIDE} selects a key file outside the protected folders")
        for verb in ("Read", "Edit"):
            add(f"{verb}({shown(path)})", cause)
    return rules


def hook_targets(settings: Mapping) -> list[Path]:
    """Absolute executables only, never run a compiled command to inspect it."""
    commands = [settings.get("apiKeyHelper")]
    hooks = settings.get("hooks", {})
    if isinstance(hooks, Mapping):
        for groups in hooks.values():
            if not isinstance(groups, list):
                continue
            for group in groups:
                if not isinstance(group, Mapping):
                    continue
                for hook in group.get("hooks", []):
                    if isinstance(hook, Mapping):
                        commands.append(hook.get("command"))
    targets: list[Path] = []
    for command in commands:
        if not isinstance(command, str):
            continue
        try:
            words = shlex.split(command)
        except ValueError:
            continue
        if words and Path(words[0]).is_absolute():
            path = Path(words[0])
            if path not in targets:
                targets.append(path)
    return targets


def missing_hook_targets(settings: Mapping) -> list[Path]:
    return [path for path in hook_targets(settings)
            if not path.is_file() or not os.access(path, os.X_OK)]


