HOOK_SHIM_RELATIVE = PurePosixPath("bin/claude-multi-hook")
GATEWAY_TOKEN_SHIM_RELATIVE = PurePosixPath("bin/claude-multi-gateway-token")


def hook_shim_path(state_root: Path | str) -> Path:
    """The stable lifecycle-hook command path embedded in compiled scopes."""

    return Path(state_root) / HOOK_SHIM_RELATIVE


def gateway_token_shim_path(state_root: Path | str) -> Path:
    """The stable apiKeyHelper path embedded in compiled scopes."""

    return Path(state_root) / GATEWAY_TOKEN_SHIM_RELATIVE


def resolve_gateway_token_path(environ: dict[str, str] | None = None) -> Path:
    """Where the loopback gateway token lives (never embedded in scopes).

    Strictly HOME-relative, matching the token's two authorities: the writer
    (``proxy.config_dir``) and the reader (launch resolves the catalog-pinned
    ``gateway.token_file`` against HOME). It deliberately does NOT follow
    ``XDG_CONFIG_HOME`` — compositions and the contract override do (via
    ``sessions.config_root``), but the token location is catalog-pinned, so
    an XDG-aware shim would point at a file the system never populates.
    """

    env = os.environ if environ is None else environ
    return Path(env.get("HOME", str(Path.home()))) / ".config" / "claude-multi" / "api-key"


# The helper's bounded wait for a start (seconds): a slow start reports
# nonzero instead of holding the client's helper call open.
TOKEN_HELPER_MAX_WAIT = 10


def gateway_token_shim_text(token_path: Path | str, launcher: str | None = None) -> bytes:
    """The apiKeyHelper shim bytes (pure).

    The shim prints the token only after ``claude-multi gateway ensure
    --quiet --max-wait 10`` reported the gateway ours and ready (a stopped
    on-demand gateway is started, bounded; only the gateway itself detaches).
    A port held by anything not proven ours, a failed or paused start and a
    timeout exit nonzero with empty stdout. The calling session's own
    destination (its compiled ``ANTHROPIC_BASE_URL``, which the client's
    environment carries into the helper) is passed as ``--base-url``: a
    session compiled for another endpoint than the configured one (the port
    changed while it ran) gets no token, so it never sends one to whatever
    now listens on its old port. ``launcher`` is the resolved launcher
    command (PATH is the fallback, like the hook shim's).
    """

    quoted_token = shlex.quote(str(token_path))
    lines = [
        "#!/bin/sh",
        "# claude-multi gateway token helper (Claude Code apiKeyHelper) - stable",
        "# path embedded in compiled scopes. Regenerated by the launcher; do",
        "# not edit. Prints the loopback gateway token from its owner-only file",
        "# only while the local gateway is proven yours and ready (a stopped",
        "# gateway is started first, bounded), so daemon-relaunched sessions keep",
        "# authenticating and no token reaches a listener that is not yours.",
    ]
    if launcher:
        lines.append(f"launcher={shlex.quote(launcher)}")
        lines.append('[ -x "$launcher" ] || launcher=$(command -v claude-multi) || launcher=')
    else:
        lines.append("launcher=$(command -v claude-multi) || launcher=")
    lines += [
        'if [ -z "$launcher" ]; then',
        "    echo 'claude-multi gateway token helper: no claude-multi launcher found' >&2",
        "    exit 1",
        "fi",
        f'set -- gateway ensure --quiet --max-wait {TOKEN_HELPER_MAX_WAIT}',
        '[ -n "${ANTHROPIC_BASE_URL-}" ] && set -- "$@" --base-url "$ANTHROPIC_BASE_URL"',
        '"$launcher" "$@" </dev/null >/dev/null || exit $?',
        f"exec cat {quoted_token}",
    ]
    return ("\n".join(lines) + "\n").encode("utf-8")


def ensure_gateway_token_shim(state_root: Path | str, token_path: Path | str,
                              launcher: str | None = None) -> Path:
    """Write/refresh the apiKeyHelper shim; return the path to embed in scopes.

    Same discipline as the hook shim: idempotent crash-safe write, mode
    repaired unconditionally. The shim prints the gateway token at runtime
    (the token itself never enters scope files), so sessions relaunched by
    the background daemon — which scrubs ANTHROPIC_* from its children's
    environment — keep their gateway routing through the compiled settings
    ``apiKeyHelper`` + ``env.ANTHROPIC_BASE_URL``.
    """

    return _ensure_executable_shim(gateway_token_shim_path(state_root),
                                   gateway_token_shim_text(token_path, launcher))


def token_helper_setting(path: Path | str) -> str:
    """The ``apiKeyHelper`` value for the shim at ``path`` (shell-quoted: the
    client runs it through a shell, and a state root may contain spaces)."""

    return shlex.quote(str(path))


def ensure_token_helper_command(
    state_root: Path | str, environ: dict[str, str] | None = None, launcher: str | None = None,
) -> str:
    """One-call resolver: ensure the token shim, return the command to embed."""

    return token_helper_setting(
        ensure_gateway_token_shim(state_root, resolve_gateway_token_path(environ), launcher)
    )


def resolve_hook_command(
    environ: Mapping[str, str] | None = None, *, installation: Path | str | None = None
) -> str:
    """The single authority for the real claude-multi command the shim execs.

    Every caller — launcher, transition engine, repair, cleanup — must derive
    the hook command here so all scopes share one spelling. Precedence:
    ``CLAUDE_MULTI_HOOK_COMMAND`` (set by the installed wrapper), then the
    running installation's own ``bin/claude-multi`` (``installation``
    replaces it in tests). Resources are not executables: a resource
    override never moves the hook command.
    """

    env = os.environ if environ is None else environ
    configured = env.get("CLAUDE_MULTI_HOOK_COMMAND")
    if configured:
        return str(Path(configured).resolve())
    entry = layout.entry_point("claude-multi", installation)
    if entry is None:
        raise ScopeError(
            "no hook command available: CLAUDE_MULTI_HOOK_COMMAND is unset "
            "and this package runs from no installation tree"
        )
    return str(entry.resolve())


def hook_shim_text(resolved_command: str) -> bytes:
    """The legacy lifecycle hook shim bytes (pure; frozen, golden-pinned).

    Factored out of :func:`ensure_hook_shim` with its bytes
    unchanged, so bless and the tests can pin the text without a write.
    """

    if not resolved_command:
        raise ScopeError("cannot write the hook shim without a resolved command")
    quoted = shlex.quote(resolved_command)
    return (
        "#!/bin/sh\n"
        "# claude-multi lifecycle hook shim - stable path embedded in compiled\n"
        "# scopes. Regenerated by the launcher; do not edit. Prefers the\n"
        "# resolved launcher command so hooks track the newest install; falls\n"
        "# back to PATH so a garbage-collected package path cannot strand them.\n"
        f"if [ -x {quoted} ]; then\n"
        f"    exec {quoted} \"$@\"\n"
        "fi\n"
        "if command -v claude-multi >/dev/null 2>&1; then\n"
        "    exec claude-multi \"$@\"\n"
        "fi\n"
        "echo 'claude-multi hook shim: no claude-multi launcher found' >&2\n"
        "exit 1\n"
    ).encode("utf-8")


def _ensure_executable_shim(path: Path, content: bytes) -> Path:
    """Write ``content`` to the shim ``path`` only on change; repair 0700.

    The shared discipline of every launcher shim: private ``bin/``,
    crash-safe ``state.atomic_write`` only when the bytes differ, and the
    mode repaired unconditionally — a crash between the atomic write and the
    chmod must never leave a permanently non-executable shim (the content
    matches, so the write would be skipped and hooks would EACCES).
    """

    state.ensure_private_dir(path.parent)
    try:
        current = state.read_private(path)
    except state.StateError:
        current = None
    if current != content:
        state.atomic_write(path, content)
    if stat.S_IMODE(os.lstat(path).st_mode) != 0o700:
        os.chmod(path, 0o700)
    return path


def ensure_hook_shim(state_root: Path | str, resolved_command: str) -> Path:
    """Write/refresh the stable hook shim; return the path to embed in scopes.

    Idempotent and crash-safe (``state.atomic_write``); only rewrites when the
    content changed. The shim prefers the resolved command (refreshed by every
    launcher invocation, so it tracks the newest installed package) and falls
    back to a PATH lookup, so hooks keep working if the exact package path was
    garbage-collected but claude-multi remains installed.
    """

    return _ensure_executable_shim(
        hook_shim_path(state_root), hook_shim_text(resolved_command)
    )


def _check_session_id(session_id: str) -> str:
    """Require the canonical lowercase UUIDv4 used by scope path names."""

    try:
        parsed = uuid.UUID(session_id)
    except (AttributeError, TypeError, ValueError) as exc:
        raise ScopeError(f"session id {session_id!r} is not a UUIDv4") from exc
    if parsed.version != 4 or str(parsed) != session_id:
        raise ScopeError(f"session id {session_id!r} is not a UUIDv4")
    return session_id


