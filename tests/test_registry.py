class RetargetNoteTests(unittest.TestCase):
    """An orphan in the chosen scope: promote prints the retarget note."""

    def setUp(self) -> None:
        self.raw = catalog.load_raw(FIXTURE_ROOT)["docs"]
        self.providers = self.raw["providers"]["providers"]
        self.lines = self.raw["models"]["models"]

    def _key(self, mode: str) -> str:
        return sorted(
            key for key, line in self.lines.items()
            if catalog.effort_mode(self.providers[line["provider"]]) == mode
        )[0]

    def test_gateway_effort_move_is_noted(self) -> None:
        key = self._key("gateway")
        after = copy.deepcopy(self.lines)
        after[key]["wire_model"] = "next-wire"
        after[key]["generation"] = "99"
        notes = dev.gateway_effort_moves(self.lines, after, self.providers)
        self.assertEqual(len(notes), 1)
        self.assertTrue(
            notes[0].startswith(
                f"running sessions of {key} retarget at the next gateway reload"
            ),
            notes[0],
        )
        self.assertIn("next-wire 99", notes[0])

    def test_client_effort_moves_new_and_unchanged_lines_are_silent(self) -> None:
        key = self._key("client")
        after = copy.deepcopy(self.lines)
        after[key]["wire_model"] = "claude-next"
        after[key]["generation"] = "99"
        after["brand-new"] = copy.deepcopy(self.lines[self._key("gateway")])
        self.assertEqual(dev.gateway_effort_moves(self.lines, after, self.providers), [])
        self.assertEqual(dev.gateway_effort_moves(self.lines, self.lines, self.providers), [])

    @uses_shipped_catalog
    def test_shipped_sonnet_generation_move_is_silent(self) -> None:
        """The shipped client-effort Sonnet move (retired
        history -> current line) prints no gateway retarget/continuity note."""
        shipped = catalog.load_raw(RESOURCES_ROOT)["docs"]
        lines = shipped["models"]["models"]
        providers = shipped["providers"]["providers"]
        history = next(row for rkey, row in shipped["retired"]["retired"].items()
                       if rkey.startswith("sonnet@") and row.get("successor") == "sonnet")
        before = copy.deepcopy(lines)
        (selector, _contract), = history["selectors"].items()
        before["sonnet"].update(wire_model=history["last_wire"], generation=history["generation"],
                                selector=selector)
        self.assertEqual(catalog.effort_mode(providers[lines["sonnet"]["provider"]]), "client")
        self.assertEqual(dev.gateway_effort_moves(before, lines, providers), [])

    def test_promote_returns_and_prints_notes_against_the_running_catalog(self) -> None:
        root = Path(tempfile.mkdtemp(prefix="claude-multi-retarget-"))
        os.chmod(root, 0o700)
        self.addCleanup(lambda: shutil.rmtree(root, ignore_errors=True))
        repo = fake_checkout(root / "repo", FIXTURE_ROOT)
        key = self._key("gateway")
        running = copy.deepcopy(self.lines)
        running[key]["wire_model"] = "older-wire"
        running[key]["generation"] = "0.9"
        draft = dev.make_model_draft(
            name="d1",
            provider="openai",
            entry={
                "id": "newmodel", "provider": "openai", "display": "New Model",
                "generation": "1", "wire_model": "gpt-new", "capabilities": ["agents"],
                "roles": ["cm-reviewer"],
                "context": {
                    "client_tokens": 128000, "provider_tokens": 128000,
                    "scalar_tokens": 128000, "ordinary_profile": None,
                    "declared_tokens": 128000, "validated_tokens": 128000,
                    "qualification": "retarget test fixture",
                },
                "efforts": {"high": {"selector": "gpt-multi-newmodel-high",
                                     "proxy_contract": "reasoning-effort-high"}},
                "default_effort": "high", "lead": None,
                "routing_note": "Fixture model for the retarget note.",
                "minimum_tested": {"claude_code": "2.1.216", "cliproxyapi": "7.3.15"},
                "status": "new", "registry_overlay": None,
            },
            now="2026-09-26T00:00:00Z",
        )
        record = dev.review_draft(
            draft, draft_name="d1", repo=repo, revision="deadbeef",
            now="2026-09-26T00:00:00Z",
            runner=lambda c, w: {"cmd": c, "returncode": 0},
            candidate_parent=Path(tempfile.mkdtemp(dir=root)),
        )
        # Without a running catalog the draft's own effect is compared: a
        # new line is never a move.
        patch_path, notes = dev.promote_patch_output(
            draft, repo=repo, output=root / "out.diff"
        )
        self.assertEqual(notes, [])
        self.assertTrue(patch_path.exists())
        self.assertEqual(
            len(dev.gateway_effort_moves(running, self.lines, self.providers)), 1
        )
        # The CLI compares against the installed (running) catalog and
        # prints each note after the promotion.
        store = dev.DraftStore(root / "state" / "claude-multi" / "drafts")
        store.save("d1", draft)
        from claude_multi import state, strict_json

        state.atomic_write(
            store.root / "d1.review.json", strict_json.canonical_file_bytes(record)
        )
        out = io.StringIO()
        with mock.patch.dict(os.environ, {"XDG_STATE_HOME": str(root / "state")}), \
                mock.patch.object(dev, "running_catalog_lines", return_value=running), \
                redirect_stdout(out):
            self.assertEqual(dev.main(["promote", "d1", "--repo", str(repo)]), 0)
        notes = [line for line in out.getvalue().splitlines() if line.startswith("note: ")]
        self.assertEqual(len(notes), 1)
        self.assertTrue(
            notes[0].startswith(
                f"note: running sessions of {key} retarget at the next gateway reload"
            ),
            notes,
        )
        post = json.loads((repo / dev.RESOURCES / "catalog" / "models.json").read_text())
        self.assertEqual(post["models"]["newmodel"]["status"], "new")


class GenerationMoveTests(unittest.TestCase):
    setUp = RetargetNoteTests.setUp
    def _key(self, mode):
        return next(key for key, entry in sorted(self.lines.items())
                    if catalog.effort_mode(self.providers[entry["provider"]]) == mode and len(entry["efforts"]) >= 2)

    def test_renamed_aliases_are_not_live_retargets(self) -> None:
        key = self._key("gateway")
        after = copy.deepcopy(self.lines)
        after[key].update(wire_model="fixture-next-wire", generation="99")
        for level, spec in after[key]["efforts"].items():
            spec["selector"] = f"gpt-multi-{key}-99-{level}[1m]"
        notes = dev.gateway_effort_moves(self.lines, after, self.providers)
        self.assertEqual(len(notes), 1)
        self.assertIn("continuity until resume", notes[0])
        self.assertNotIn("retarget", notes[0])
        with self.assertRaisesRegex(dev.DevError, "--from-json"):
            docs = copy.deepcopy(self.raw)
            docs["models"]["models"] = after
            dev._scaffold_model_entry(docs, like_id=key, new_id="fixture-new", wire_model="fixture-new-wire")

    def test_partial_rename_and_client_suffix_change_are_not_misreported(self) -> None:
        key = self._key("gateway")
        after = copy.deepcopy(self.lines)
        after[key].update(wire_model="fixture-next-wire", generation="99")
        levels = list(after[key]["efforts"])
        self.assertGreaterEqual(len(levels), 2)
        after[key]["efforts"][levels[0]]["selector"] = "gpt-multi-fixture-renamed"
        notes = dev.gateway_effort_moves(self.lines, after, self.providers)
        self.assertEqual(len(notes), 2)
        self.assertIn("retarget", notes[0])
        self.assertIn("continuity until resume", notes[1])
        after = copy.deepcopy(self.lines)
        after[key].update(wire_model="fixture-next-wire", generation="99")
        for spec in after[key]["efforts"].values():
            spec["selector"] = spec["selector"].removesuffix("[1m]")
