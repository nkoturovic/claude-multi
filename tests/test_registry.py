def _oauth_lines(raw_docs):
    providers = raw_docs["providers"]["providers"]
    return {
        key: line
        for key, line in raw_docs["models"]["models"].items()
        if catalog.registry_section(providers[line["provider"]]) is not None
    }


# The pinned upstream registry snapshot (generated by `tools/build.py gateway
# registry` from the pinned source; the Nix package build compares it with
# that source byte for byte). A gateway re-pin regenerates it and updates
# these recorded identities in the same change.
REGISTRY_SNAPSHOT_SHA256 = {
    "models.json": "ca457e5269f67068fcd13de77a4eb55da603917cd77309e61e4661ef4327c85b",
    "codex_client_models.json": "7b15fec55ed279c2a0f4b6dfd1f7d2617d7c9f22e94d385242a8cd9534411d38",
}


class RegistryDirTests(unittest.TestCase):
    def test_env_override_and_explicitly_absent_directory(self) -> None:
        self.assertEqual(
            catalog.registry_dir({catalog.REGISTRY_DIR_ENV: str(REGISTRY_FIXTURE)}),
            REGISTRY_FIXTURE,
        )
        self.assertIsNone(
            catalog.registry_dir({catalog.REGISTRY_DIR_ENV: str(REGISTRY_FIXTURE / "nope")})
        )

    def test_the_packaged_snapshot_is_the_default(self) -> None:
        # Resources carry the pinned snapshot: no override selects it.
        self.assertEqual(catalog.registry_dir({}), RESOURCES_ROOT / "registry")
        self.assertEqual(REGISTRY_SNAPSHOT, RESOURCES_ROOT / "registry")
        registry = catalog.load_pinned_registry(catalog.registry_dir({}))
        # Every account pool's sections are in the pinned registry.
        for pool in account_pools.pools().values():
            with self.subTest(pool=pool.name):
                self.assertLessEqual(set(pool.registry_sections), set(registry.sections))

    def test_an_explicit_resource_root_selects_its_own_registry(self) -> None:
        # Resources follow the selected root: explicit > CLAUDE_MULTI_ASSETS >
        # packaged. The frozen fixture root carries none.
        self.assertIsNone(catalog.registry_dir({}, FIXTURE_ROOT))
        self.assertIsNone(catalog.registry_dir({"CLAUDE_MULTI_ASSETS": str(FIXTURE_ROOT)}))
        self.assertEqual(catalog.registry_dir({"CLAUDE_MULTI_ASSETS": str(FIXTURE_ROOT)}, RESOURCES_ROOT),
                         RESOURCES_ROOT / "registry")
        self.assertEqual(catalog.registry_dir({catalog.REGISTRY_DIR_ENV: str(REGISTRY_FIXTURE)}, RESOURCES_ROOT),
                         REGISTRY_FIXTURE)


class RegistrySnapshotTests(unittest.TestCase):
    """The checked-in snapshot keeps its recorded identity (one content
    authority: the pinned upstream source, through the build tool)."""

    def test_recorded_identity(self) -> None:
        self.assertEqual(sorted(path.name for path in REGISTRY_SNAPSHOT.iterdir()),
                         sorted(catalog.REGISTRY_FILES))
        for name, digest in REGISTRY_SNAPSHOT_SHA256.items():
            with self.subTest(name=name):
                self.assertEqual(hashlib.sha256((REGISTRY_SNAPSHOT / name).read_bytes()).hexdigest(), digest)
        self.assertEqual(set(REGISTRY_SNAPSHOT_SHA256), set(catalog.REGISTRY_FILES))

    def test_the_build_tool_and_the_package_name_the_same_files(self) -> None:
        from _layout import BUILD_TOOL, NIX_DIR, load_tool

        build = load_tool("build")
        self.assertEqual(Path(BUILD_TOOL).name, "build.py")
        self.assertEqual(build.DEFAULT_REGISTRY, REGISTRY_SNAPSHOT)
        self.assertEqual(build.REGISTRY_FILES, catalog.REGISTRY_FILES)
        package = (NIX_DIR / "package.nix").read_text()
        self.assertIn("for name in " + " ".join(catalog.REGISTRY_FILES) + "; do", package)
        self.assertIn('cmp -s "${cliProxyApiRegistry}/$name"', package)

    @unittest.skipUnless(os.environ.get("CLAUDE_MULTI_TEST_UPSTREAM_SOURCE"),
                         "BOUNDARY: CLAUDE_MULTI_TEST_UPSTREAM_SOURCE names no pinned upstream source tree")
    def test_snapshot_equals_the_pinned_source(self) -> None:
        source = Path(os.environ["CLAUDE_MULTI_TEST_UPSTREAM_SOURCE"]) / "internal" / "registry" / "models"
        for name in catalog.REGISTRY_FILES:
            with self.subTest(name=name):
                self.assertEqual((REGISTRY_SNAPSHOT / name).read_bytes(), (source / name).read_bytes())


class PinnedRegistryTests(unittest.TestCase):
    def setUp(self) -> None:
        self.registry = catalog.load_pinned_registry(REGISTRY_FIXTURE)
        self.raw = catalog.load_raw(FIXTURE_ROOT)["docs"]

    def test_sections_and_codex_metadata(self) -> None:
        self.assertIn("claude", self.registry.sections)
        self.assertIn(account_pools.pool("codex").registry_section, self.registry.sections)
        # Retirement data stays reachable for the doctor radar.
        retiring = {
            slug: fields["retirement_at"]
            for slug, fields in self.registry.codex.items()
            if fields["retirement_at"]
        }
        self.assertEqual(retiring, {"gpt-5.5": "2026-10-14T19:00:00Z"})
        self.assertEqual(self.registry.codex["gpt-5.5"]["upgrade"], "gpt-5.6-sol")
        self.assertEqual(self.registry.codex["gpt-5.5"]["visibility"], "list")

    def test_only_oauth_pools_have_a_section(self) -> None:
        providers = self.raw["providers"]["providers"]
        sections = {pid: catalog.registry_section(p) for pid, p in providers.items()}
        for pid, provider in providers.items():
            with self.subTest(provider=pid):
                if provider["transport"]["kind"] == "oauth-pool":
                    self.assertIsNotNone(sections[pid])
                else:
                    self.assertIsNone(sections[pid])
        codex = [p for p in providers.values() if p["transport"].get("pool") == "codex"]
        self.assertTrue(codex)
        self.assertEqual(catalog.registry_section(codex[0]), "codex-pro")

    def test_fixture_catalog_is_fully_present(self) -> None:
        self.assertTrue(_oauth_lines(self.raw))
        self.assertEqual(
            catalog.registry_absent_wires(
                self.raw["models"]["models"], self.raw["providers"]["providers"], self.registry
            ),
            [],
        )

    def test_absent_wire_is_flagged_new_lines_included(self) -> None:
        models = copy.deepcopy(self.raw["models"]["models"])
        providers = self.raw["providers"]["providers"]
        key = sorted(_oauth_lines(self.raw))[0]
        models[key]["wire_model"] = "wire-the-registry-lacks"
        models[key]["status"] = "new"
        section = catalog.registry_section(providers[models[key]["provider"]])
        self.assertEqual(
            catalog.registry_absent_wires(models, providers, self.registry),
            [(key, "wire-the-registry-lacks", section)],
        )

    def test_tier_matters(self) -> None:
        # The fixture keeps the pinned tier difference: codex-free lacks a
        # wire codex-pro carries, so the rule reads codex-pro only.
        free = self.registry.sections["codex-free"]
        pro = self.registry.sections["codex-pro"]
        self.assertTrue(pro - free)

    def test_malformed_registry_raises(self) -> None:
        root = Path(tempfile.mkdtemp(prefix="claude-multi-registry-"))
        self.addCleanup(lambda: shutil.rmtree(root, ignore_errors=True))
        for models, codex in (
            ("[]", '{"models": []}'),
            ('{"claude": {}}', '{"models": []}'),
            ('{"claude": []}', '{"nope": []}'),
            ("not json", '{"models": []}'),
        ):
            with self.subTest(models=models, codex=codex):
                (root / "models.json").write_text(models)
                (root / "codex_client_models.json").write_text(codex)
                with self.assertRaises(catalog.CatalogError):
                    catalog.load_pinned_registry(root)


class RegistryMetaTests(unittest.TestCase):
    """Bounded, advisory ``PinnedRegistry.meta``."""

    def write(self, models: dict, codex: dict | None = None) -> Path:
        root = Path(tempfile.mkdtemp(prefix="claude-multi-registry-meta-"))
        self.addCleanup(lambda: shutil.rmtree(root, ignore_errors=True))
        (root / "models.json").write_text(json.dumps(models))
        (root / "codex_client_models.json").write_text(json.dumps(codex or {"models": []}))
        return root

    def test_fixture_meta_matches_the_frozen_cut(self) -> None:
        registry = catalog.load_pinned_registry(REGISTRY_FIXTURE)
        raw = json.loads((REGISTRY_FIXTURE / "models.json").read_text())
        for section, items in raw.items():
            self.assertEqual(set(registry.meta[section]), registry.sections[section])
            for item in items:
                with self.subTest(section=section, wire=item["id"]):
                    meta = registry.meta[section][item["id"]]
                    self.assertEqual(meta.context_length, item.get("context_length"))
                    self.assertEqual(meta.max_completion_tokens, item.get("max_completion_tokens"))
                    self.assertEqual(meta.created, item.get("created"))
                    self.assertEqual(meta.display_name, item.get("display_name"))

    def test_malformed_fields_are_none_and_sections_unchanged(self) -> None:
        good = {"id": "wire-a", "display_name": "Wire A", "context_length": 400000,
                "max_completion_tokens": 64000, "created": 1790000000,
                "thinking": {"levels": ["low", "high", "xhigh"]}}
        bad = {"id": "wire-b", "display_name": "x" * 97, "context_length": True,
               "max_completion_tokens": 2**31, "created": -1, "thinking": {"levels": ["high", "turbo"]}}
        control = {"id": "wire-c", "display_name": "evil\x1b[31m", "context_length": "400000",
                   "created": 1.5, "thinking": {"levels": "high"}}
        empty = {"id": "wire-d", "display_name": " ", "thinking": {"levels": []}}
        dup = {"id": "wire-e", "thinking": {"levels": ["high", "high"]}}
        root = self.write({"claude": [good, bad, control, empty, dup, {"id": "../bad"}, "junk"]})
        registry = catalog.load_pinned_registry(root)
        self.assertEqual(registry.sections["claude"], frozenset({"wire-a", "wire-b", "wire-c", "wire-d", "wire-e"}))
        self.assertEqual(registry.meta["claude"]["wire-a"], catalog.RegistryModel(
            "Wire A", 400000, 64000, ("low", "high", "xhigh"), 1790000000))
        for wire in ("wire-b", "wire-c", "wire-d", "wire-e"):
            with self.subTest(wire=wire):
                self.assertEqual(registry.meta["claude"][wire], catalog.RegistryModel())

    def test_conflicting_duplicates_keep_presence_and_become_unknown(self) -> None:
        first = {"id": "wire-a", "display_name": "A", "context_length": 400000, "created": 10,
                 "thinking": {"levels": ["high"]}}
        second = {"id": "wire-a", "display_name": "A", "context_length": 272000, "created": 10,
                  "thinking": {"levels": ["high", "xhigh"]}}
        registry = catalog.load_pinned_registry(self.write({"codex-pro": [first, second]}))
        self.assertIn("wire-a", registry.sections["codex-pro"])
        self.assertEqual(registry.meta["codex-pro"]["wire-a"],
                         catalog.RegistryModel("A", None, None, None, 10))

    def test_codex_upgrade_metadata_is_untouched(self) -> None:
        codex = {"models": [{"slug": "wire-a", "visibility": "hide", "upgrade": {"model": "wire-b"}}]}
        registry = catalog.load_pinned_registry(self.write({"codex-pro": [{"id": "wire-a"}]}, codex))
        self.assertEqual(registry.codex["wire-a"], {"visibility": "hide", "upgrade": "wire-b", "retirement_at": None})

    def test_meta_is_advisory_only(self) -> None:
        # No registry value becomes a context validation, contract, admission
        # or fence input: the catalog modules that own those never read meta.
        for module in ("profile.py", "scope.py", "compiler.py", "settings.py", "render.py"):
            with self.subTest(module=module):
                text = (REPO_ROOT / "src" / "claude_multi" / module).read_text()
                self.assertNotIn(".meta[", text)
                self.assertNotIn("RegistryModel", text)


